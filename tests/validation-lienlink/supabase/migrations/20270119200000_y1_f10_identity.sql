CREATE OR REPLACE FUNCTION better_supabase.get_team (
  team uuid
)
  RETURNS jsonb
  LANGUAGE plpgsql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
#variable_conflict use_variable
declare
  v_tenant uuid;
  v_row jsonb;
begin
  select x."tenant_id", jsonb_build_object(
    'id', x."id",
    'name', x."name",
    'slug', x."slug",
    'description', x."description",
    'status', x."status",
    'member_ids', coalesce((
      select jsonb_agg(m."user_id" order by m."created_at")
      from "better_supabase"."team_members" m
      where m."team_id" = x."id"
    ), '[]'::jsonb)
  )
    into v_tenant, v_row
    from "better_supabase"."teams" x
    where x."id" = get_team.team;
  if v_row is null then
    return null;
  end if;
  if not (auth.role() = 'service_role' or coalesce(better_supabase.can('tenant', v_tenant, 'teams.read'), false)) then
    raise exception 'not allowed to read teams' using errcode = '42501', hint = 'TEAM_FORBIDDEN';
  end if;
  return v_row;
end;
$function$;

