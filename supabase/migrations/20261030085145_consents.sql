CREATE TABLE "better_supabase"."consent_purposes" (
  "id"                 uuid                     NOT NULL DEFAULT gen_random_uuid(),
  "tenant_id"          uuid,
  "key"                text                     NOT NULL,
  "title"              text                     NOT NULL,
  "description"        text,
  "legal_basis"        text                     NOT NULL DEFAULT 'consent'::text,
  "version"            text                     NOT NULL DEFAULT '1'::text,
  "requires_signature" boolean                  NOT NULL DEFAULT false,
  "valid_months"       integer,
  "archived_at"        timestamp with time zone,
  "created_at"         timestamp with time zone NOT NULL DEFAULT now(),
  "updated_at"         timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT "consent_purposes_description_check" CHECK (((description IS NULL) OR (length(description) <= 4000))),
  CONSTRAINT "consent_purposes_key_check" CHECK ((key ~ '^[a-z][a-z0-9_.-]{0,62}$'::text)),
  CONSTRAINT "consent_purposes_legal_basis_check"
    CHECK ((legal_basis = ANY (ARRAY['consent'::text, 'contract'::text, 'legal_obligation'::text, 'vital_interest'::text, 'public_task'::text, 'legitimate_interest'::text]))),
  CONSTRAINT "consent_purposes_pkey" PRIMARY KEY (id),
  CONSTRAINT "consent_purposes_title_check" CHECK (((length(title) >= 1) AND (length(title) <= 200))),
  CONSTRAINT "consent_purposes_valid_months_check" CHECK (((valid_months IS NULL) OR ((valid_months >= 1) AND (valid_months <= 1200)))),
  CONSTRAINT "consent_purposes_version_check" CHECK (((length(version) >= 1) AND (length(version) <= 40)))
);

