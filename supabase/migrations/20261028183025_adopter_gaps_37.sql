CREATE OR REPLACE FUNCTION better_supabase.reorder_product_options (
  product uuid,
  options uuid[]
)
  RETURNS boolean
  LANGUAGE plpgsql
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
declare
  v_tenant uuid;
  v_rank text;
  v_option uuid;
begin
