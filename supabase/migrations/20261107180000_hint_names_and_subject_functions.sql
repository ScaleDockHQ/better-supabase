CREATE OR REPLACE FUNCTION better_supabase.append_only_guard()
  RETURNS TRIGGER
  LANGUAGE plpgsql
  SET search_path TO ''
  AS $function$
begin
  raise exception '% is append-only', tg_table_name
    using errcode = '42501', hint = 'TABLE_APPEND_ONLY';
end;
$function$;

