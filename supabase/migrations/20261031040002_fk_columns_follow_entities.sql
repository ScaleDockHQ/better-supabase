CREATE OR REPLACE FUNCTION better_supabase.engagement_guest_readable (
  engagement uuid
)
  RETURNS boolean
  LANGUAGE sql
  STABLE
  SECURITY DEFINER
  SET search_path TO ''
  AS $function$
  select exists (
    select 1 from "better_supabase"."activities" x
    join "better_supabase"."engagement_subjects" k on k."activity_id" = x."id"
