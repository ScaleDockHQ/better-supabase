// Copies an adopter project (CentraKit) to a temporary directory, renders its SQL with the baseline
// release, runs the 0.82 codemods, renders again and prints what the cutover changed. The source
// project is never written to. Usage: node scripts/cutover-report.ts [--source <dir>]
// [--baseline <git ref>] [--skip-prune] [--keep] [--json] [--strict]
import { spawnSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  statSync,
} from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join, relative, resolve } from "node:path";
import { argv, exit } from "node:process";
import { fileURLToPath } from "node:url";

export const CONFIG_LINE_TARGET = 3000;

export type SectionCounts = Map<string, number>;

export interface Snapshot {
  files: Map<string, string>;
}

export interface FileDiff {
  file: string;
  kind: "added" | "removed" | "changed";
  added: string[];
  removed: string[];
}

export interface AllowlistEntry {
  name: string;
  pattern: RegExp;
}

// A rendered change is explained when the file path or the changed line matches one of these.
export const ALLOWLIST: AllowlistEntry[] = [
  { name: "tax_codes", pattern: /tax_codes|tax_rates|tax_code_id|tax_code\b/i },
  { name: "cancel hooks", pattern: /cancel/i },
  {
    name: "numbering default",
    pattern: /numbering|next_number|number_format|padding|sequence_name/i,
  },
  {
    name: "feature gating",
    pattern:
      /feature|gated|_disabled|externalRecipients|external_recipients|e_endpoints|e_deliveries|dunning/i,
  },
  {
    name: "clone and import functions",
    pattern:
      /clone_|import_|instantiate_template|enqueue_import|copy_header|resolve_address|resolveAddress/i,
  },
  {
    name: "render comments and signatures",
    pattern:
      /^--|^\s*--|bsb:|generated by|better_supabase_version|module_version/i,
  },
];

const CONFIG_START = /^export default defineConfig\(\{\s*$/;
const SECTION_KEY = /^ {2}("[^"]+"|[A-Za-z_$][\w$]*)\s*[:(]/;
const ENTRY_KEY = /^ {4}("[^"]+"|[A-Za-z_$][\w$]*)\s*[:(]/;

// Lines per top-level key of defineConfig; the lines before it count as "preamble".
export function configSections(source: string): SectionCounts {
  const lines = source.split("\n");

  if (lines.at(-1) === "") {
    lines.pop();
  }

  const start = lines.findIndex((line) => CONFIG_START.test(line));
  const counts: SectionCounts = new Map();

  if (start === -1) {
    counts.set("(whole file)", lines.length);

    return counts;
  }

  counts.set("preamble", start + 1);
  let current: string | null = null;

  for (const line of lines.slice(start + 1)) {
    const key = SECTION_KEY.exec(line)?.[1];

    if (key !== undefined) {
      current = key.replaceAll('"', "");
    }

    const name = current ?? "preamble";
    counts.set(name, (counts.get(name) ?? 0) + 1);
  }

  return counts;
}

const ARRAY_ENTRY = /^ {4}\{/;
const BLOCK_NAME = /\bblock:\s*"([^"]+)"/;

// Lines per block of the `blocks` section (an object keyed by name or a list), for the
// largest-entries list. Several instances of one block add up.
export function blockEntrySizes(source: string): SectionCounts {
  const entries: { name: string; lines: number }[] = [];
  let inBlocks = false;
  let open = false;

  for (const line of source.split("\n")) {
    const section = SECTION_KEY.exec(line)?.[1];

    if (section !== undefined) {
      inBlocks = section === "blocks";
      open = false;
      continue;
    }

    if (!inBlocks) {
      continue;
    }

    if (/^ {2}\S/.test(line)) {
      open = false;
      continue;
    }

    const key = ENTRY_KEY.exec(line)?.[1];

    if (key !== undefined || ARRAY_ENTRY.test(line)) {
      entries.push({ name: key?.replaceAll('"', "") ?? "(unnamed)", lines: 0 });
      open = true;
    }

    const entry = entries.at(-1);

    if (open && entry !== undefined) {
      const named = BLOCK_NAME.exec(line)?.[1];

      if (named !== undefined && entry.name === "(unnamed)") {
        entry.name = named;
      }

      entry.lines += 1;
    }
  }

  const sizes: SectionCounts = new Map();

  for (const entry of entries) {
    sizes.set(entry.name, (sizes.get(entry.name) ?? 0) + entry.lines);
  }

  return sizes;
}

export function totalLines(counts: SectionCounts): number {
  return [...counts.values()].reduce((sum, value) => sum + value, 0);
}

function walk(root: string, dir: string, into: Map<string, string>): void {
  if (!existsSync(dir)) {
    return;
  }

  for (const name of readdirSync(dir).toSorted((a, b) => a.localeCompare(b))) {
    const path = join(dir, name);

    if (statSync(path).isDirectory()) {
      walk(root, path, into);
    } else {
      into.set(relative(root, path), readFileSync(path, "utf-8"));
    }
  }
}

// The files `upgrade` writes: block modules, block data, the adopted-table files and migrations.
export function snapshotSql(appDir: string): Snapshot {
  const files = new Map<string, string>();
  walk(appDir, join(appDir, "supabase/better-supabase-data"), files);
  walk(appDir, join(appDir, "supabase/schemas/better_supabase"), files);
  walk(appDir, join(appDir, "supabase/migrations"), files);

  return { files };
}

function lineSet(text: string): string[] {
  return text.split("\n").filter((line) => line.trim() !== "");
}

export function diffSnapshots(before: Snapshot, after: Snapshot): FileDiff[] {
  const diffs: FileDiff[] = [];
  const names = new Set([...before.files.keys(), ...after.files.keys()]);

  for (const file of [...names].toSorted((a, b) => a.localeCompare(b))) {
    const old = before.files.get(file);
    const next = after.files.get(file);

    if (old === next) {
      continue;
    }

    if (old === undefined) {
      diffs.push({
        file,
        kind: "added",
        added: lineSet(next ?? ""),
        removed: [],
      });
    } else if (next === undefined) {
      diffs.push({ file, kind: "removed", added: [], removed: lineSet(old) });
    } else {
      const oldLines = lineSet(old);
      const nextLines = lineSet(next);
      const oldCount = new Map<string, number>();

      for (const line of oldLines) {
        oldCount.set(line, (oldCount.get(line) ?? 0) + 1);
      }

      const added: string[] = [];

      for (const line of nextLines) {
        const left = oldCount.get(line) ?? 0;

        if (left > 0) {
          oldCount.set(line, left - 1);
        } else {
          added.push(line);
        }
      }

      const removed: string[] = [];

      for (const [line, count] of oldCount) {
        for (let index = 0; index < count; index += 1) {
          removed.push(line);
        }
      }

      if (added.length > 0 || removed.length > 0) {
        diffs.push({ file, kind: "changed", added, removed });
      }
    }
  }

  return diffs;
}

export interface Classified {
  explained: Record<string, number>;
  unexplained: { file: string; lines: string[] }[];
}

function classifyLine(
  file: string,
  line: string,
  allowlist: AllowlistEntry[],
): string | null {
  for (const entry of allowlist) {
    if (entry.pattern.test(file) || entry.pattern.test(line)) {
      return entry.name;
    }
  }

  return null;
}

export function classifyDiffs(
  diffs: FileDiff[],
  allowlist: AllowlistEntry[] = ALLOWLIST,
): Classified {
  const explained: Record<string, number> = {};
  const unexplained: Classified["unexplained"] = [];

  for (const diff of diffs) {
    const rest: string[] = [];

    for (const line of [...diff.removed, ...diff.added]) {
      const name = classifyLine(diff.file, line, allowlist);

      if (name === null) {
        rest.push(line);
      } else {
        explained[name] = (explained[name] ?? 0) + 1;
      }
    }

    if (rest.length > 0) {
      unexplained.push({ file: diff.file, lines: rest });
    }
  }

  return { explained, unexplained };
}

export interface Deletable {
  file: string;
  exists: boolean;
  replacedBy: string;
  deletable: boolean;
  reason: string;
}

function readIfExists(path: string): string | null {
  return existsSync(path) ? readFileSync(path, "utf-8") : null;
}

function findFiles(dir: string, name: RegExp, into: string[] = []): string[] {
  if (!existsSync(dir)) {
    return into;
  }

  for (const entry of readdirSync(dir)) {
    if (
      entry === "node_modules" ||
      entry === ".git" ||
      entry.startsWith(".next")
    ) {
      continue;
    }

    const path = join(dir, entry);

    if (statSync(path).isDirectory()) {
      findFiles(path, name, into);
    } else if (name.test(entry)) {
      into.push(path);
    }
  }

  return into;
}

// Adopter files the 0.82 features replace. A file is deletable when it exists and the feature that
// replaces it is present in the rendered project.
export function deletableFiles(
  appDir: string,
  afterConfig: string,
): Deletable[] {
  const result: Deletable[] = [];

  const secretFields = findFiles(
    join(appDir, "supabase/schemas"),
    /^secret_fields\.sql$/,
  );

  for (const path of secretFields) {
    result.push({
      file: relative(appDir, path),
      exists: true,
      replacedBy: "@bsb encrypted tags",
      deletable: true,
      reason: "the seal trigger skips bsf1: values since 0.79",
    });
  }

  if (secretFields.length === 0) {
    result.push({
      file: "supabase/schemas/**/secret_fields.sql",
      exists: false,
      replacedBy: "@bsb encrypted tags",
      deletable: false,
      reason: "not in the project",
    });
  }

  const db = readIfExists(join(appDir, "packages/supabase-runtime/src/db.ts"));
  result.push({
    file: "packages/supabase-runtime/src/db.ts (insertableFields and *FieldsSchema)",
    exists: db !== null,
    replacedBy: "the fields export of each block slice",
    deletable: db !== null && /insertableFields|FieldsSchema/.test(db),
    reason:
      "a not-null column with a default is optional on insert in the generated schema",
  });
  const genFunctions = /gen:\s*\{[\s\S]*?functions:\s*\{/.test(afterConfig);
  result.push({
    file: "better-supabase.config.ts gen.functions",
    exists: genFunctions,
    replacedBy: "not-null results declared in the block manifests",
    deletable: genFunctions,
    reason: "BS427 reports entries that restate a declared result",
  });

  const overrides = findFiles(
    join(appDir, "supabase/schemas"),
    /import.*override|imports?_runner/i,
  );

  for (const path of overrides) {
    result.push({
      file: relative(appDir, path),
      exists: true,
      replacedBy:
        "import_upsert_batch, import_apply_batch and cancel_import_run in the module",
      deletable: true,
      reason:
        "the module covers the conflict rows, dry-run cleanup and chunk retry",
    });
  }

  return result;
}

interface Options {
  source: string;
  baseline: string | null;
  skipPrune: boolean;
  keep: boolean;
  json: boolean;
  strict: boolean;
}

export function parseArgs(args: string[]): Options {
  const options: Options = {
    source: resolve(homedir(), "Documents/Code/CentraKit"),
    baseline: null,
    skipPrune: false,
    keep: false,
    json: false,
    strict: false,
  };

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index] ?? "";

    switch (arg) {
      case "--source": {
        options.source = resolve(args[(index += 1)] ?? options.source);
        break;
      }

      case "--baseline": {
        options.baseline = args[(index += 1)] ?? null;
        break;
      }

      case "--skip-prune": {
        options.skipPrune = true;
        break;
      }

      case "--keep": {
        options.keep = true;
        break;
      }

      case "--json": {
        options.json = true;
        break;
      }

      case "--strict": {
        options.strict = true;
        break;
      }

      default: {
        throw new Error(`Unknown option ${arg}`);
      }
    }
  }

  return options;
}

function run(command: string, args: string[], cwd: string): string {
  const result = spawnSync(command, args, {
    cwd,
    encoding: "utf-8",
    maxBuffer: 512 * 1024 * 1024,
  });

  if (result.status !== 0) {
    throw new Error(
      `${command} ${args.join(" ")} exited ${String(result.status)}\n${result.stdout.slice(-2000)}\n${result.stderr.slice(-2000)}`,
    );
  }

  return result.stdout;
}

function copyProject(source: string, target: string): void {
  const clone = spawnSync(
    "rsync",
    [
      "-a",
      ...[".git", ".next", ".turbo", ".cache", ".swc", ".vercel"].map(
        (name) => `--exclude=${name}`,
      ),
      `${source}/`,
      `${target}/`,
    ],
    { stdio: "ignore" },
  );

  if (clone.status !== 0) {
    cpSync(source, target, { recursive: true });
  }
}

function linkModules(repo: string, worktree: string): void {
  symlinkSync(join(repo, "node_modules"), join(worktree, "node_modules"));

  for (const name of readdirSync(join(repo, "packages"))) {
    const modules = join(repo, "packages", name, "node_modules");

    if (existsSync(modules)) {
      symlinkSync(modules, join(worktree, "packages", name, "node_modules"));
    }
  }
}

function cli(root: string): string {
  return join(root, "packages/better-supabase/src/cli/bin.ts");
}

const CLI_FLAGS = ["--yes", "--non-interactive", "--json", "--no-color"];

function printSections(
  title: string,
  before: SectionCounts,
  after: SectionCounts,
): void {
  console.log(`\n${title}`);
  const names = new Set([...before.keys(), ...after.keys()]);

  const rows = [...names]
    .map((name) => ({
      name,
      before: before.get(name) ?? 0,
      after: after.get(name) ?? 0,
    }))
    .toSorted((a, b) => b.before - a.before);

  for (const row of rows) {
    console.log(
      `  ${row.name.padEnd(18)} ${String(row.before).padStart(5)} -> ${String(row.after).padStart(5)}`,
    );
  }

  console.log(
    `  ${"total".padEnd(18)} ${String(totalLines(before)).padStart(5)} -> ${String(totalLines(after)).padStart(5)}`,
  );
}

function main(): number {
  const options = parseArgs(argv.slice(2));
  const repo = resolve(fileURLToPath(new URL("..", import.meta.url)));
  const work = mkdtempSync(join(tmpdir(), "cutover-"));
  const app = join(work, "app");
  const base = join(work, "base");

  try {
    console.log(`Copying ${options.source} to ${app}`);
    copyProject(options.source, app);

    const ref =
      options.baseline ??
      run("git", ["merge-base", "main", "HEAD"], repo).trim();

    run("git", ["worktree", "add", "--detach", base, ref], repo);
    linkModules(repo, base);
    const configPath = join(app, "better-supabase.config.ts");
    const before = readFileSync(configPath, "utf-8");

    console.log(`Rendering with the baseline at ${ref.slice(0, 10)}`);
    run("node", [cli(base), "upgrade", ...CLI_FLAGS, "--no-cache"], app);
    const baselineSql = snapshotSql(app);

    const codemods = [
      ["blocks-list"],
      ...(options.skipPrune ? [] : [["config", "--prune"]]),
      ["record-types"],
      ["table-tags"],
      ["doctor-baseline"],
    ];

    for (const args of codemods) {
      console.log(`Codemod ${args.join(" ")}`);
      run("node", [cli(repo), "codemod", ...args, ...CLI_FLAGS], app);
    }

    const after = readFileSync(configPath, "utf-8");

    console.log("Rendering with the current source");
    run("node", [cli(repo), "upgrade", ...CLI_FLAGS, "--no-cache"], app);
    const currentSql = snapshotSql(app);

    const sectionsBefore = configSections(before);
    const sectionsAfter = configSections(after);
    printSections(
      "Config lines per section (before -> after)",
      sectionsBefore,
      sectionsAfter,
    );
    const total = totalLines(sectionsAfter);
    console.log(
      `\nTarget under ${String(CONFIG_LINE_TARGET)} lines: ${total < CONFIG_LINE_TARGET ? "met" : `not met (${String(total - CONFIG_LINE_TARGET + 1)} lines over)`}`,
    );

    const largest = [...blockEntrySizes(after)]
      .toSorted((a, b) => b[1] - a[1])
      .slice(0, 10);

    console.log("Largest blocks entries after:");

    for (const [name, lines] of largest) {
      console.log(`  ${name.padEnd(28)} ${String(lines).padStart(5)}`);
    }

    const diffs = diffSnapshots(baselineSql, currentSql);
    const classified = classifyDiffs(diffs);
    console.log(`\nRendered SQL: ${String(diffs.length)} files differ`);

    for (const [name, count] of Object.entries(classified.explained)) {
      console.log(`  allowlisted ${name}: ${String(count)} lines`);
    }

    console.log(
      `  unexplained files: ${String(classified.unexplained.length)}`,
    );

    for (const item of classified.unexplained.slice(0, 20)) {
      console.log(`    ${item.file} (${String(item.lines.length)} lines)`);

      for (const line of item.lines.slice(0, 3)) {
        console.log(`      ${line.slice(0, 140)}`);
      }
    }

    const deletable = deletableFiles(app, after);
    console.log("\nAdopter files");

    for (const item of deletable) {
      console.log(
        `  ${item.deletable ? "deletable" : "keep     "} ${item.file} (${item.replacedBy})`,
      );
    }

    if (options.json) {
      console.log(
        JSON.stringify(
          { sectionsBefore, sectionsAfter, classified, deletable },
          null,
          2,
        ),
      );
    }

    if (options.keep) {
      console.log(`\nKept ${work}`);
    }

    return options.strict && classified.unexplained.length > 0 ? 1 : 0;
  } finally {
    spawnSync("git", ["worktree", "remove", "--force", base], {
      cwd: repo,
      stdio: "ignore",
    });

    if (!options.keep) {
      rmSync(work, { recursive: true, force: true });
    }
  }
}

if (resolve(argv[1] ?? "") === import.meta.filename) {
  mkdirSync(tmpdir(), { recursive: true });
  exit(main());
}
