/**
 * Builds `src/blocks/hint-codes.generated.ts`: the hint codes each block's
 * errors carry, as string literal unions. They come from the `hint = '…'` the
 * `raise` and `fail` helpers render into the block's SQL with default options,
 * and from the `hint: "…"` literals in the block's TypeScript client.
 */
import { globSync, readFileSync } from "node:fs";
import { join } from "node:path";

import type { AnyBlock } from "../packages/better-supabase/src/blocks/define-block.ts";

import { renderBlocks } from "../packages/better-supabase/src/sql/index.ts";

const CODE = /^[A-Z][A-Z0-9_]*$/;

/** A subject with a record team, so the SQL that needs one renders its hints. */
const TEAM_SUBJECT = {
  record: { table: "public.records", team: { actions: ["read"] } },
} as const;

/** The same subject with read logging, which needs the audit block. */
const READ_SUBJECT = {
  record: { ...TEAM_SUBJECT.record, auditReads: true },
} as const;

/** The module's files with read logging on, or none when it can't render so. */
function readLoggedFiles(names: readonly string[]) {
  try {
    return renderBlocks([...names, "subjects", "audit"], {
      subjects: READ_SUBJECT,
    });
  } catch {
    return [];
  }
}

const SQL_BY_MODULE = new Map<string, string>();

/** The SQL of `module`, rendered next to the modules it needs most often. */
function moduleSql(module: string): string {
  const known = SQL_BY_MODULE.get(module);

  if (known !== undefined) {
    return known;
  }

  const sql = renderModuleSql(module);

  SQL_BY_MODULE.set(module, sql);

  return sql;
}

function renderModuleSql(module: string): string {
  for (const names of [
    [module, "outbox"],
    [module, "outbox", "organizations"],
  ]) {
    try {
      return [
        ...[names, [...names, "subjects"]].flatMap((each) =>
          renderBlocks(each, { subjects: TEAM_SUBJECT }),
        ),
        ...readLoggedFiles(names),
      ]
        .filter((file) => file.module === module)
        .map((file) => file.contents)
        .join("\n");
    } catch {
      continue;
    }
  }

  return "";
}

function clientHints(blocksSrc: string, block: string): readonly string[] {
  return globSync(join(blocksSrc, block, "**/*.ts")).flatMap((file) =>
    [
      ...readFileSync(file, "utf-8").matchAll(
        /(?:hint|code):\s*"([A-Z][A-Z0-9_]*)"/g,
      ),
    ].flatMap((match) => (match[1] === undefined ? [] : [match[1]])),
  );
}

/** The hint codes of every block, by block name, sorted. */
export function blockHints(
  manifests: readonly AnyBlock[],
  blocksSrc: string,
): ReadonlyMap<string, readonly string[]> {
  const sql = new Map<string, readonly string[]>();

  const hintsOf = (module: string): readonly string[] => {
    const known = sql.get(module);

    if (known !== undefined) {
      return known;
    }

    const found = [...moduleSql(module).matchAll(/hint = '([^']+)'/g)].flatMap(
      (match) => (match[1] === undefined ? [] : [match[1]]),
    );

    sql.set(module, found);

    return found;
  };

  return new Map(
    manifests
      .map((manifest): [string, readonly string[]] => [
        manifest.name,
        [
          ...new Set([
            ...manifest.sql.flatMap(hintsOf),
            ...clientHints(blocksSrc, manifest.name),
          ]),
        ]
          .filter((hint) => CODE.test(hint))
          .toSorted(),
      ])
      .filter(([, hints]) => hints.length > 0)
      .toSorted(([a], [b]) => a.localeCompare(b)),
  );
}

/** The contents of `hint-codes.generated.ts`. */
export function formatBlockHints(
  hints: ReadonlyMap<string, readonly string[]>,
): string {
  return [
    "// Generated by scripts/build-catalog.ts from the block SQL and clients. Do",
    "// not edit; run `pnpm catalog`.",
    "",
    "/** The hint codes each block's errors can carry, by block name. */",
    "export interface BlockHints {",
    ...[...hints].map(
      ([block, codes]) =>
        `  readonly ${JSON.stringify(block)}: ${codes.map((code) => JSON.stringify(code)).join(" | ")};`,
    ),
    "}",
    "",
  ].join("\n");
}

const RAISE =
  /raise exception '((?:[^']|'')*)'([^;]*?)hint = '([A-Z][A-Z0-9_]*)'/gs;

/** `text` with a capital and a final full stop. */
function sentenceOf(text: string): string {
  const trimmed = text.trim();
  const capital = `${trimmed.charAt(0).toUpperCase()}${trimmed.slice(1)}`;

  return /[.!?]$/.test(capital) ? capital : `${capital}.`;
}

/** `TASK_NOT_FOUND` as `Task not found.`, for a code whose SQL names no message. */
function wordsOf(code: string): string {
  return sentenceOf(code.toLowerCase().replaceAll("_", " "));
}

/**
 * One English message per hint code. It is the message the SQL raises the code
 * with (first block in name order wins), unless that message has a `%`
 * placeholder, and then it is the code in words.
 */
export function blockHintMessages(
  manifests: readonly AnyBlock[],
  hints: ReadonlyMap<string, readonly string[]>,
): ReadonlyMap<string, string> {
  const messages = new Map<string, string>();

  for (const manifest of manifests.toSorted((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    for (const module of manifest.sql) {
      for (const match of moduleSql(module).matchAll(RAISE)) {
        const [, raw, , code] = match;

        if (
          raw !== undefined &&
          code !== undefined &&
          !raw.includes("%") &&
          !messages.has(code)
        ) {
          messages.set(code, sentenceOf(raw.replaceAll("''", "'")));
        }
      }
    }
  }

  const codes = new Set([...hints.values()].flat());

  return new Map(
    [...codes]
      .toSorted()
      .map((code): [string, string] => [
        code,
        messages.get(code) ?? wordsOf(code),
      ]),
  );
}

/** The contents of `hint-messages.generated.ts`. */
export function formatBlockHintMessages(
  messages: ReadonlyMap<string, string>,
): string {
  return [
    "// Generated by scripts/build-catalog.ts from the block SQL. Do not edit;",
    "// run `pnpm catalog`.",
    "",
    'import type { BlockHint } from "../block-hints.ts";',
    "",
    "/**",
    " * The default English message of every hint code. The code is also the",
    " * next-intl key: `messages: { blockErrors: BLOCK_HINT_MESSAGES }`.",
    " */",
    "export const BLOCK_HINT_MESSAGES: Readonly<Record<BlockHint, string>> = {",
    ...[...messages].map(
      ([code, message]) =>
        `  ${JSON.stringify(code)}: ${JSON.stringify(message)},`,
    ),
    "};",
    "",
  ].join("\n");
}
