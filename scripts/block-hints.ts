/**
 * Builds `src/blocks/hint-codes.generated.ts`: the hint codes each block's
 * errors carry, as string literal unions. They come from the `hint = '…'` the
 * `raise` and `fail` helpers render into the block's SQL with default options,
 * and from the `hint: "…"` literals in the block's TypeScript client.
 */
import { globSync, readFileSync } from "node:fs";
import { join } from "node:path";

import type { AnyBlock } from "../packages/better-supabase/src/blocks/define-block.ts";

import { renderBlocks } from "../packages/better-supabase/src/sql/index.ts";

const CODE = /^[A-Z][A-Z0-9_]*$/;

/** A subject with a record team, so the SQL that needs one renders its hints. */
const TEAM_SUBJECT = {
  record: { table: "public.records", team: { actions: ["read"] } },
} as const;

/** The same subject with read logging, which needs the audit block. */
const READ_SUBJECT = {
  record: { ...TEAM_SUBJECT.record, auditReads: true },
} as const;

/** The module's files with read logging on, or none when it can't render so. */
function readLoggedFiles(names: readonly string[]) {
  try {
    return renderBlocks([...names, "subjects", "audit"], {
      subjects: READ_SUBJECT,
    });
  } catch {
    return [];
  }
}

/** The SQL of `module`, rendered next to the modules it needs most often. */
function moduleSql(module: string): string {
  for (const names of [
    [module, "outbox"],
    [module, "outbox", "organizations"],
  ]) {
    try {
      return [
        ...[names, [...names, "subjects"]].flatMap((each) =>
          renderBlocks(each, { subjects: TEAM_SUBJECT }),
        ),
        ...readLoggedFiles(names),
      ]
        .filter((file) => file.module === module)
        .map((file) => file.contents)
        .join("\n");
    } catch {
      continue;
    }
  }

  return "";
}

function clientHints(blocksSrc: string, block: string): readonly string[] {
  return globSync(join(blocksSrc, block, "**/*.ts")).flatMap((file) =>
    [...readFileSync(file, "utf-8").matchAll(/hint:\s*"([^"]+)"/g)].flatMap(
      (match) => (match[1] === undefined ? [] : [match[1]]),
    ),
  );
}

/** The hint codes of every block, by block name, sorted. */
export function blockHints(
  manifests: readonly AnyBlock[],
  blocksSrc: string,
): ReadonlyMap<string, readonly string[]> {
  const sql = new Map<string, readonly string[]>();

  const hintsOf = (module: string): readonly string[] => {
    const known = sql.get(module);

    if (known !== undefined) {
      return known;
    }

    const found = [...moduleSql(module).matchAll(/hint = '([^']+)'/g)].flatMap(
      (match) => (match[1] === undefined ? [] : [match[1]]),
    );

    sql.set(module, found);

    return found;
  };

  return new Map(
    manifests
      .map((manifest): [string, readonly string[]] => [
        manifest.name,
        [
          ...new Set([
            ...manifest.sql.flatMap(hintsOf),
            ...clientHints(blocksSrc, manifest.name),
          ]),
        ]
          .filter((hint) => CODE.test(hint))
          .toSorted(),
      ])
      .filter(([, hints]) => hints.length > 0)
      .toSorted(([a], [b]) => a.localeCompare(b)),
  );
}

/** The contents of `hint-codes.generated.ts`. */
export function formatBlockHints(
  hints: ReadonlyMap<string, readonly string[]>,
): string {
  return [
    "// Generated by scripts/build-catalog.ts from the block SQL and clients. Do",
    "// not edit; run `pnpm catalog`.",
    "",
    "/** The hint codes each block's errors can carry, by block name. */",
    "export interface BlockHints {",
    ...[...hints].map(
      ([block, codes]) =>
        `  readonly ${JSON.stringify(block)}: ${codes.map((code) => JSON.stringify(code)).join(" | ")};`,
    ),
    "}",
    "",
  ].join("\n");
}
