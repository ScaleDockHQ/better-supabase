import { existsSync } from "node:fs";
import {
  copyFile,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { runScaffoldScreens } from "../../../src/cli/commands/scaffold.ts";
import { run } from "../../../src/cli/core/run.ts";
import {
  type BetterSupabaseConfig,
  resolveConfig,
} from "../../../src/config/index.ts";

let dir = "";

const FIXTURE_META = new URL(
  "../../fixtures/generated-camel.meta.js",
  import.meta.url,
);

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "better-supabase-scaffold-"));
  await mkdir(join(dir, "src/lib/supabase"), { recursive: true });
});

afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

const project = async (dependencies: Record<string, string>, meta = true) => {
  await writeFile(
    join(dir, "package.json"),
    JSON.stringify({ name: "app", dependencies }),
  );

  if (meta) {
    await copyFile(
      FIXTURE_META,
      join(dir, "src/lib/supabase/generated.meta.js"),
    );
  }
};

const scaffold = (...args: string[]) =>
  run(["scaffold", ...args, "--cwd", dir]);

const read = (path: string): Promise<string> =>
  readFile(join(dir, path), "utf-8");

describe("scaffold api", () => {
  it("writes the Next.js catch-all and OpenAPI routes for every public table", async () => {
    await project({ next: "16.0.0" });
    const result = await scaffold("api");
    expect(result.stderr).toBe("");
    expect(result.code).toBe(0);
    expect(result.stdout).toContain("Created src/app/api/[...path]/route.ts");
    expect(result.stdout).toContain("specs: { entry: 'src/lib/api.ts' }");
    const generated = await read("src/lib/api.generated.ts");
    expect(generated).toMatch(/^\/\/ @generated by better-supabase scaffold/);
    expect(generated).toContain('"customers"');
    expect(generated).toContain('export const basePath = "/api";');
    expect(await read("src/app/api/[...path]/route.ts")).toContain(
      "bs.resources(resources, { basePath })",
    );
    expect(await read("src/app/api/openapi.json/route.ts")).toContain(
      "specResponse(document, request)",
    );
    expect(await read("src/lib/api.ts")).toContain("from './supabase';");
  });

  it("rewrites the generated file and keeps the hand-owned ones", async () => {
    await project({ hono: "4.0.0" });
    expect((await scaffold("api", "--tables", "customers")).code).toBe(0);
    await writeFile(join(dir, "src/lib/api.ts"), "// mine\n");

    const again = await scaffold(
      "api",
      "--tables",
      "customers,notes",
      "--base-path",
      "v1/",
    );

    expect(again.stdout).toContain(
      "Skipped src/lib/api.ts (exists; pass --force to overwrite)",
    );
    expect(again.stdout).toContain("Updated src/lib/api.generated.ts");
    expect(again.stdout).toContain(".route('/', apiRoutes(bs))");
    expect(await read("src/lib/api.ts")).toBe("// mine\n");
    expect(await read("src/lib/api.generated.ts")).toContain(
      'export const basePath = "/v1";',
    );
    expect(await read("src/api-routes.ts")).toContain("bs.resource(table)");

    const same = await scaffold(
      "api",
      "--tables",
      "customers,notes",
      "--base-path",
      "/v1",
    );

    expect(same.stdout).toContain("Unchanged src/lib/api.generated.ts");
  });

  it("refuses to overwrite a file it did not write", async () => {
    await project({ hono: "4.0.0" });
    await writeFile(join(dir, "src/lib/api.generated.ts"), "export {};\n");
    const result = await scaffold("api");
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("not generated by better-supabase");
  });

  it("explains missing or wrong input", async () => {
    await project({ next: "16.0.0", hono: "4.0.0" });
    expect((await scaffold()).code).toBe(2);
    expect((await scaffold("app")).code).toBe(2);
    expect((await scaffold("api")).stderr).toContain("Pass --framework");
    expect((await scaffold("api", "--framework", "express")).stderr).toContain(
      'got "express"',
    );
    expect(
      (await scaffold("api", "--framework", "next", "--name", "a/b")).code,
    ).toBe(2);

    const unknown = await scaffold(
      "api",
      "--framework",
      "next",
      "--tables",
      "ghosts",
    );

    expect(unknown.stderr).toContain("Unknown tables: ghosts");
  });

  it("needs gen output or --tables", async () => {
    await project({ next: "16.0.0" }, false);
    const missing = await scaffold("api");
    expect(missing.code).toBe(1);
    expect(missing.stderr).toContain("Run `better-supabase gen` first");
    expect((await scaffold("api", "--tables", "orders")).code).toBe(0);
  });

  it("prints the scaffold.api entry for the flags it was given", async () => {
    await project({ next: "16.0.0", hono: "4.0.0" });

    const result = await scaffold(
      "api",
      "--framework",
      "hono",
      "--tables",
      "customers",
      "--base-path",
      "v1",
    );

    expect(result.stdout).toContain(
      "scaffold: { api: { framework: 'hono', basePath: '/v1', tables: ['customers'] } }",
    );
  });
});

describe("scaffold from the config", () => {
  const configure = (api: object) =>
    writeFile(
      join(dir, "better-supabase.config.json"),
      JSON.stringify({ scaffold: { api } }),
    );

  it("reads the flags from scaffold.api", async () => {
    await project({ next: "16.0.0", hono: "4.0.0" });
    await configure({
      framework: "hono",
      tables: ["customers"],
      basePath: "/v2",
    });
    const result = await scaffold("api");
    expect(result.code).toBe(0);
    expect(result.stdout).not.toContain("scaffold: { api:");
    expect(await read("src/lib/api.generated.ts")).toContain(
      'export const basePath = "/v2";',
    );
  });

  it("lets a flag win over scaffold.api", async () => {
    await project({ hono: "4.0.0" });
    await configure({ framework: "hono", basePath: "/v2" });
    expect((await scaffold("api", "--base-path", "/v3")).code).toBe(0);
    expect(await read("src/lib/api.generated.ts")).toContain(
      'export const basePath = "/v3";',
    );
  });

  it("runs as a gen task: the generated file only, and --check", async () => {
    await project({ hono: "4.0.0" });
    await configure({ framework: "hono", tables: ["customers"] });

    const gen = (...args: string[]) =>
      run(["gen", "--only", "scaffold", ...args, "--cwd", dir]);

    const stale = await gen("--check");
    expect(stale.code).toBe(1);
    expect(stale.stderr).toContain("src/lib/api.generated.ts is out of date");
    expect(stale.stdout).toContain("+++ src/lib/api.generated.ts\tgenerated");

    const written = await gen();
    expect(written.stderr).toBe("");
    expect(written.code).toBe(0);
    expect(written.stdout).toContain("Created src/lib/api.generated.ts");
    expect(written.stdout).not.toContain("Next:");
    await expect(read("src/lib/api.ts")).rejects.toThrow(/ENOENT/);

    const current = await gen("--check");
    expect(current.code).toBe(0);
    expect(current.stdout).toContain("src/lib/api.generated.ts is up to date.");
  });
});

describe("scaffold screens", () => {
  const APP_TABLES: BetterSupabaseConfig["appTables"] = {
    projects: {
      columns: { name: { type: "text", nullable: false, max: 200 } },
      subject: { type: "project", title: "name" },
    },
    tasks: {
      columns: {
        title: { type: "text", nullable: false },
        status: {
          type: "text",
          nullable: false,
          options: ["todo", "doing", "done"],
          default: "'todo'",
        },
        project_id: {
          type: "uuid",
          nullable: false,
          references: { table: "projects" },
        },
        estimate: { type: "integer", min: 0 },
        due_on: { type: "date" },
        done: { type: "boolean", default: "false" },
        meta: { type: "jsonb", default: "'{}'" },
      },
    },
  };

  const screens = (
    table: string | undefined,
    config: BetterSupabaseConfig = {},
    flags: Record<string, string> = {},
  ) =>
    runScaffoldScreens(
      resolveConfig({ casing: "camel", appTables: APP_TABLES, ...config }, dir),
      { ...(table === undefined ? {} : { table }), ...flags },
    );

  it("writes list, create and detail pages from the app table", async () => {
    await project({ next: "16.0.0" }, false);
    const result = await screens("tasks");
    expect(result.error).toBeUndefined();
    expect(result.code).toBe(0);
    expect(result.output).toContain("Created src/app/tasks/page.tsx");
    expect(result.output).toContain("record-* recipes");

    const list = await read("src/app/tasks/page.tsx");
    expect(list).toContain("from '../../lib/supabase/server';");
    expect(list).toContain("bs.require({ requireTenant: true })");
    expect(list).toContain(
      "select: ['id', 'title', 'status', 'projectId', 'estimate', 'dueOn']",
    );
    expect(list).toContain("where: { organizationId: tenant }");
    expect(list).toContain("orderBy: { createdAt: 'desc' }");

    const form = await read("src/app/tasks/form.tsx");
    expect(form).toContain('<option value="doing">doing</option>');
    expect(form).toContain('type="number" min={0}');
    expect(form).toContain('type="date"');
    expect(form).toContain('<input type="checkbox" name="done" />');
    expect(form).not.toContain('name="meta"');

    const actions = await read("src/app/tasks/actions.ts");
    expect(actions).toContain("projectId: required(form, 'project_id'),");
    expect(actions).toContain(
      "estimate: map(optional(form, 'estimate'), Number),",
    );
    expect(actions).toContain("done: form.get('done') === 'on',");
    expect(actions).toContain("organizationId: tenant");
    expect(actions).not.toContain("toTimestamp");

    const create = await read("src/app/tasks/new/page.tsx");
    expect(create).toContain(
      "db.projects.findMany({ select: ['id', 'name'], limit: 200 })",
    );

    const detail = await read("src/app/tasks/[id]/page.tsx");
    expect(detail).toContain("notFound();");
    expect(detail).toContain("where: { id, organizationId: tenant }");
  });

  it("keeps pages that exist and follows --base-path", async () => {
    await project({ next: "16.0.0" }, false);
    await mkdir(join(dir, "src/app/(app)/work"), { recursive: true });
    await writeFile(join(dir, "src/app/(app)/work/page.tsx"), "// mine\n");

    const result = await screens("projects", {}, { "base-path": "(app)/work" });
    expect(result.code).toBe(0);
    expect(result.output).toContain("Skipped src/app/(app)/work/page.tsx");
    expect(await read("src/app/(app)/work/page.tsx")).toBe("// mine\n");
    expect(await read("src/app/(app)/work/actions.ts")).toContain(
      "redirect(`/work/",
    );
  });

  it("scopes per user and leaves the tenant out", async () => {
    await project({ next: "16.0.0" }, false);
    const result = await screens("projects", { sql: { scope: "user" } });
    expect(result.code).toBe(0);
    const list = await read("src/app/projects/page.tsx");
    expect(list).toContain("const { db } = await bs.require();");
    expect(list).not.toContain("tenant");
  });

  it("refuses what it can't serve", async () => {
    await project({ next: "16.0.0" }, false);
    await expect(screens(undefined)).rejects.toThrow("Name the app table");
    expect((await screens("nope")).error).toContain(
      "App tables: projects, tasks.",
    );
    expect(
      (await screens("tasks", { appTables: { tasks: { scope: "none" } } }))
        .error,
    ).toContain('scope "none"');
    expect(
      (
        await screens("tasks", {
          appTables: {
            tasks: { columns: { tags: { type: "text[]", nullable: false } } },
          },
        })
      ).error,
    ).toContain("tasks.tags is required");
    expect(
      (await screens("tasks", {}, { "base-path": "tasks/[id]" })).error,
    ).toContain("static route");
  });

  it("maps every column type and codec to an input and a parse", async () => {
    await project({ next: "16.0.0" }, false);

    const LEDGER: BetterSupabaseConfig["appTables"] = {
      entries: {
        id: "bigint",
        subject: { type: "entry", softDelete: true },
        columns: {
          contact: { type: "text", format: "email" },
          site: { type: "text", format: "url" },
          phone: { type: "text", format: "phone" },
          body: { type: "text", format: "long_text", max: 500 },
          shade: { type: "text", format: "color" },
          score: { type: "integer", format: "rating" },
          kind: { type: "text", options: ["a", "b"] },
          owner: { type: "uuid", references: { table: "auth.users" } },
          ref: { type: "uuid" },
          amount: { type: "numeric", min: 0, max: 10 },
          total: { type: "bigint", nullable: false, default: "0" },
          paid: { type: "boolean", default: "true" },
          at: { type: "timestamptz" },
          external: { type: "uuid", default: "gen_random_uuid()" },
        },
      },
    };

    const codecs = {
      int8: "string",
      numeric: "string",
      timestamptz: "string",
    } as const;

    const result = await screens("entries", {
      appTables: LEDGER,
      codecs,
      sql: { naming: { tenant: "workspace" } },
    });

    expect(result.error).toBeUndefined();

    const form = await read("src/app/entries/form.tsx");

    for (const type of ["email", "url", "tel", "color", "datetime-local"]) {
      expect(form).toContain(`type="${type}"`);
    }

    expect(form).toContain('<textarea id="body" name="body" maxLength={500}');
    expect(form).toContain('<option value="">None</option>');
    expect(form).toContain('step="any"');
    expect(form).toContain("defaultChecked");
    expect(form).not.toContain('name="external"');

    const actions = await read("src/app/entries/actions.ts");
    expect(actions).toContain("amount: optional(form, 'amount'),");
    expect(actions).toContain("total: required(form, 'total'),");
    expect(actions).toContain("at: map(optional(form, 'at'), toTimestamp),");

    const detail = await read("src/app/entries/[id]/page.tsx");
    expect(detail).toContain(String.raw`/^\d+$/`);
    expect(detail).toContain(
      "where: { id, workspaceId: tenant, deletedAt: { isNull: true } }",
    );

    for (const int8 of ["bigint", "number"] as const) {
      await rm(join(dir, "src/app"), { recursive: true, force: true });
      await screens("entries", {
        appTables: LEDGER,
        codecs: { int8, numeric: "number", timestamptz: "instant" },
      });
      const parse = int8 === "bigint" ? "BigInt" : "Number";
      expect(await read("src/app/entries/actions.ts")).toContain(
        `total: ${parse}(required(form, 'total')),`,
      );
      expect(await read("src/app/entries/[id]/page.tsx")).toContain(
        `${parse}(id)`,
      );
    }

    expect(await read("src/app/entries/actions.ts")).toContain(
      "amount: map(optional(form, 'amount'), Number),",
    );
  });

  it("refuses a required timestamp the instant codec can't fill", async () => {
    await project({ next: "16.0.0" }, false);

    const result = await screens("tasks", {
      codecs: { timestamptz: "instant" },
      appTables: {
        tasks: { columns: { at: { type: "timestamptz", nullable: false } } },
      },
    });

    expect(result.error).toContain("tasks.at is required");
  });

  it("needs Next.js", async () => {
    await project({ hono: "4.0.0" }, false);
    await expect(screens("tasks")).rejects.toThrow("Screens are Next.js pages");
    await expect(screens("tasks", {}, { framework: "hono" })).rejects.toThrow(
      "--framework hono has none",
    );
  });

  it("prints the pages under --dry-run and writes nothing", async () => {
    await project({ next: "16.0.0" }, false);

    const result = await runScaffoldScreens(
      resolveConfig({ casing: "camel", appTables: APP_TABLES }, dir),
      { table: "tasks", "dry-run": true },
    );

    expect(result.code).toBe(0);
    expect(result.output).toContain("Would create src/app/tasks/page.tsx");
    expect(result.data).toMatchObject({ table: "tasks", basePath: "/tasks" });
    expect(existsSync(join(dir, "src/app/tasks/page.tsx"))).toBe(false);
  });
});
