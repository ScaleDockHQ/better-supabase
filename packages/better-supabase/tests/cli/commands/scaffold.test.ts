import {
  copyFile,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { run } from "../../../src/cli/run.ts";

let dir = "";

const FIXTURE_META = new URL(
  "../../fixtures/generated-camel.meta.js",
  import.meta.url,
);

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "better-supabase-scaffold-"));
  await mkdir(join(dir, "src/lib/supabase"), { recursive: true });
});

afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

const project = async (dependencies: Record<string, string>, meta = true) => {
  await writeFile(
    join(dir, "package.json"),
    JSON.stringify({ name: "app", dependencies }),
  );
  if (meta)
    await copyFile(
      FIXTURE_META,
      join(dir, "src/lib/supabase/generated.meta.js"),
    );
};

const scaffold = (...args: string[]) =>
  run(["scaffold", ...args, "--cwd", dir]);

const read = (path: string): Promise<string> =>
  readFile(join(dir, path), "utf8");

describe("scaffold api", () => {
  it("writes the Next.js catch-all and OpenAPI routes for every public table", async () => {
    await project({ next: "16.0.0" });
    const result = await scaffold("api");
    expect(result.stderr).toBe("");
    expect(result.code).toBe(0);
    expect(result.stdout).toContain("Wrote src/app/api/[...path]/route.ts");
    expect(result.stdout).toContain("specs: { entry: 'src/lib/api.ts' }");
    const generated = await read("src/lib/api.generated.ts");
    expect(generated).toMatch(/^\/\/ @generated by better-supabase scaffold/);
    expect(generated).toContain('"customers"');
    expect(generated).toContain('export const basePath = "/api";');
    expect(await read("src/app/api/[...path]/route.ts")).toContain(
      "bs.resources(resources, { basePath })",
    );
    expect(await read("src/app/api/openapi.json/route.ts")).toContain(
      "specResponse(document, request)",
    );
    expect(await read("src/lib/api.ts")).toContain("from './supabase';");
  });

  it("rewrites the generated file and keeps the hand-owned ones", async () => {
    await project({ hono: "4.0.0" });
    expect((await scaffold("api", "--tables", "customers")).code).toBe(0);
    await writeFile(join(dir, "src/lib/api.ts"), "// mine\n");
    const again = await scaffold(
      "api",
      "--tables",
      "customers,notes",
      "--base-path",
      "v1/",
    );
    expect(again.stdout).toContain("Kept src/lib/api.ts (yours)");
    expect(again.stdout).toContain("Wrote src/lib/api.generated.ts");
    expect(again.stdout).toContain(".route('/', apiRoutes(bs))");
    expect(await read("src/lib/api.ts")).toBe("// mine\n");
    expect(await read("src/lib/api.generated.ts")).toContain(
      'export const basePath = "/v1";',
    );
    expect(await read("src/api-routes.ts")).toContain("bs.resource(table)");
    const same = await scaffold(
      "api",
      "--tables",
      "customers,notes",
      "--base-path",
      "/v1",
    );
    expect(same.stdout).toContain("Unchanged src/lib/api.generated.ts");
  });

  it("refuses to overwrite a file it did not write", async () => {
    await project({ hono: "4.0.0" });
    await writeFile(join(dir, "src/lib/api.generated.ts"), "export {};\n");
    const result = await scaffold("api");
    expect(result.code).toBe(1);
    expect(result.stderr).toContain("not written by better-supabase scaffold");
  });

  it("explains missing or wrong input", async () => {
    await project({ next: "16.0.0", hono: "4.0.0" });
    expect((await scaffold()).code).toBe(2);
    expect((await scaffold("app")).code).toBe(2);
    expect((await scaffold("api")).stderr).toContain("Pass --framework");
    expect((await scaffold("api", "--framework", "express")).stderr).toContain(
      'got "express"',
    );
    expect(
      (await scaffold("api", "--framework", "next", "--name", "a/b")).code,
    ).toBe(2);
    const unknown = await scaffold(
      "api",
      "--framework",
      "next",
      "--tables",
      "ghosts",
    );
    expect(unknown.stderr).toContain("Unknown tables: ghosts");
  });

  it("needs gen output or --tables", async () => {
    await project({ next: "16.0.0" }, false);
    const missing = await scaffold("api");
    expect(missing.code).toBe(1);
    expect(missing.stderr).toContain("Run `better-supabase gen` first");
    expect((await scaffold("api", "--tables", "orders")).code).toBe(0);
  });
});
