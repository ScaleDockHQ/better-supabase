import { describe, expect, it } from "vitest";

import {
  powersyncColumnType,
  powersyncOutput,
  publicationSql,
} from "../../../src/cli/powersync/streams.ts";
import { resolveConfig } from "../../../src/config/index.ts";
import { moduleLayout, renderBlocks } from "../../../src/sql/index.ts";

const BLOCKS = ["memberships", "notifications", "attachments"] as const;

const config = resolveConfig(
  { blocks: Object.fromEntries(BLOCKS.map((name) => [name, {}])) },
  "/p",
);

const files = renderBlocks(config.blockNames, moduleLayout(config));

const output = powersyncOutput({
  files,
  instances: [
    { key: "notifications", block: "notifications" },
    { key: "attachments", block: "attachments" },
  ],
  importFrom: "@powersync/common",
});

describe("powersyncColumnType", () => {
  it("syncs integers and booleans as integer, floats as real and the rest as text", () => {
    expect(powersyncColumnType("bigint")).toBe("integer");
    expect(powersyncColumnType("boolean")).toBe("integer");
    expect(powersyncColumnType("numeric(12, 2)")).toBe("real");
    expect(powersyncColumnType("double precision")).toBe("real");
    expect(powersyncColumnType("integer[]")).toBe("text");
    expect(powersyncColumnType("timestamptz")).toBe("text");
    expect(powersyncColumnType("jsonb")).toBe("text");
    expect(powersyncColumnType("uuid")).toBe("text");
  });
});

describe("powersyncOutput", () => {
  it("names the tables of each instance", () => {
    expect(output.tables).toEqual({
      notifications: [
        "notification_recipients",
        "notification_events",
        "notification_preferences",
      ],
      attachments: ["attachments"],
    });
  });

  it("streams the user's recipients, their events and the files of their organizations", () => {
    expect(output.streams).toMatch(/^# @generated by better-supabase gen/);
    expect(output.streams).toContain("config:\n  edition: 3\n");

    expect(output.streams).toContain(
      '  notifications_recipients:\n    auto_subscribe: true\n    query: "SELECT * FROM better_supabase.notification_recipients WHERE user_id = auth.user_id()"',
    );

    expect(output.streams).toContain(
      'query: "SELECT * FROM better_supabase.notification_events WHERE id IN (SELECT event_id FROM better_supabase.notification_recipients WHERE user_id = auth.user_id())"',
    );

    expect(output.streams).toContain(
      'active_orgs: "SELECT organization_id FROM better_supabase.memberships WHERE user_id = auth.user_id() AND disabled_at IS NULL"',
    );

    expect(output.streams).toContain(
      'query: "SELECT * FROM better_supabase.attachments WHERE organization_id IN active_orgs"',
    );
  });

  it("creates the powersync publication with each table once", () => {
    expect(output.publication).toContain(
      "create publication powersync for table better_supabase.notification_recipients, better_supabase.notification_events, better_supabase.notification_preferences, better_supabase.attachments;",
    );
  });

  it("adds only the tables an earlier publication migration lacks", () => {
    expect(
      publicationSql(
        ["better_supabase.attachments", "better_supabase.notification_events"],
        new Set(["better_supabase.attachments"]),
      ),
    ).toContain(
      "alter publication powersync add table better_supabase.notification_events;",
    );

    expect(
      publicationSql(
        ["better_supabase.attachments"],
        new Set(["better_supabase.attachments"]),
      ),
    ).toBeUndefined();
  });

  it("syncs files only where a role reads them, when roles gate the read key", () => {
    const gated = powersyncOutput({
      files,
      instances: [{ key: "attachments", block: "attachments" }],
      readRoles: new Map([["attachments", ["owner", "it's"]]]),
      importFrom: "@powersync/common",
    });

    expect(gated.streams).toContain(
      `reader_orgs: "SELECT organization_id FROM better_supabase.memberships WHERE user_id = auth.user_id() AND (role = 'owner' OR role = 'it''s')"`,
    );

    expect(gated.streams).toContain(
      "WHERE organization_id IN active_orgs AND organization_id IN reader_orgs",
    );
  });

  it("writes a Table per synced table without the id column", () => {
    expect(output.schema).toContain(
      'import { column, Table } from "@powersync/common";',
    );

    expect(output.schema).toMatch(
      /export const notification_recipients = new Table\(\{[^}]*read_at: column\.text,/,
    );

    expect(output.schema).not.toMatch(/^ {2}id: column/m);

    expect(output.schema).toContain(
      "export const blockTables = { notification_recipients, notification_events, notification_preferences, attachments };",
    );
  });

  it("refuses attachments without memberships", () => {
    expect(() =>
      powersyncOutput({
        files: files.filter((file) => file.module !== "memberships"),
        instances: [{ key: "attachments", block: "attachments" }],
        importFrom: "@powersync/common",
      }),
    ).toThrow(/needs the memberships block/);
  });
});

describe("powersyncOutput for memberships, teams and profiles", () => {
  const scoped = resolveConfig(
    {
      blocks: Object.fromEntries(
        ["memberships", "organizations", "teams", "profiles"].map((name) => [
          name,
          {},
        ]),
      ),
    },
    "/p",
  );

  const scopedFiles = renderBlocks(scoped.blockNames, moduleLayout(scoped));

  const synced = powersyncOutput({
    files: scopedFiles,
    instances: [
      { key: "memberships", block: "memberships" },
      { key: "teams", block: "teams" },
      { key: "profiles", block: "profiles" },
    ],
    importFrom: "@powersync/common",
  });

  it("names the tables of each instance", () => {
    expect(synced.tables).toEqual({
      memberships: ["memberships", "organizations"],
      teams: ["teams", "team_members"],
      profiles: ["profiles"],
    });
  });

  it("keys memberships and team members by both columns and streams the user's own", () => {
    expect(synced.streams).toContain(
      `query: "SELECT organization_id || ':' || user_id AS id, * FROM better_supabase.memberships WHERE user_id = auth.user_id() AND disabled_at IS NULL"`,
    );

    expect(synced.streams).toContain(
      `query: "SELECT team_id || ':' || user_id AS id, * FROM better_supabase.team_members WHERE tenant_id IN my_orgs"`,
    );

    expect(synced.streams).toContain(
      'query: "SELECT * FROM better_supabase.teams WHERE tenant_id IN my_orgs"',
    );

    expect(synced.streams).toContain(
      'my_orgs: "SELECT organization_id FROM better_supabase.memberships WHERE user_id = auth.user_id() AND disabled_at IS NULL"',
    );

    expect(synced.streams).toContain(
      'query: "SELECT * FROM better_supabase.profiles WHERE id = auth.user_id()"',
    );
  });

  it("streams only the switcher's columns of the user's organizations", () => {
    expect(synced.streams).toContain(
      'query: "SELECT id, name, slug, disabled_at, deleted_at FROM better_supabase.organizations WHERE id IN (SELECT organization_id FROM better_supabase.memberships WHERE user_id = auth.user_id() AND disabled_at IS NULL)"',
    );

    expect(synced.schema).not.toMatch(
      /export const organizations = new Table\(\{[^}]*created_by/,
    );
  });

  it("streams memberships without organization names when the organizations block is absent", () => {
    const alone = powersyncOutput({
      files: scopedFiles.filter((file) => file.module !== "organizations"),
      instances: [{ key: "memberships", block: "memberships" }],
      importFrom: "@powersync/common",
    });

    expect(alone.tables).toEqual({ memberships: ["memberships"] });
  });

  it("syncs the role set with a composite id and never takes it for the memberships", () => {
    const roles = powersyncOutput({
      files: renderBlocks(["memberships"], {
        modules: { memberships: { options: { roles: { many: true } } } },
      }),
      instances: [{ key: "memberships", block: "memberships" }],
      importFrom: "@powersync/common",
    });

    expect(roles.tables).toEqual({
      memberships: ["memberships", "membership_roles"],
    });

    expect(roles.streams).toContain(
      `query: "SELECT organization_id || ':' || user_id || ':' || role AS id, * FROM better_supabase.membership_roles WHERE user_id = auth.user_id()"`,
    );

    expect(roles.streams).toContain(
      "FROM better_supabase.memberships WHERE user_id = auth.user_id() AND disabled_at IS NULL",
    );
  });

  it("syncs columns that a later alter table adds", () => {
    const extended = powersyncOutput({
      files: [
        ...scopedFiles,
        {
          path: "supabase/schemas/zz.sql",
          module: "app",
          kind: "schema",
          contents:
            "alter table better_supabase.memberships add column if not exists last_seen_at timestamptz;",
        },
      ],
      instances: [{ key: "memberships", block: "memberships" }],
      importFrom: "@powersync/common",
    });

    expect(extended.schema).toMatch(
      /export const memberships = new Table\(\{[^}]*last_seen_at: column\.text/,
    );
  });
});

describe("powersyncOutput refusals", () => {
  it("refuses attachments without memberships", () => {
    expect(() =>
      powersyncOutput({
        files: files.filter((file) => file.module !== "memberships"),
        instances: [{ key: "attachments", block: "attachments" }],
        importFrom: "@powersync/common",
      }),
    ).toThrow(/needs the memberships block/);
  });
});

describe("powersyncOutput over the app's tables", () => {
  const adopted = powersyncOutput({
    files: [],
    instances: [{ key: "memberships", block: "memberships" }],
    own: new Map([
      [
        "memberships",
        new Map([
          [
            "public.memberships",
            new Map([
              ["organization_id", "uuid"],
              ["user_id", "uuid"],
              ["role", "text"],
            ]),
          ],
        ]),
      ],
      [
        "organizations",
        new Map([
          [
            "public.organizations",
            new Map([
              ["id", "uuid"],
              ["name", "text"],
              ["seats", "int4"],
            ]),
          ],
        ]),
      ],
    ]),
    importFrom: "@powersync/common",
  });

  it("streams an adopted memberships table and its organizations", () => {
    expect(adopted.streams).toContain(
      `query: "SELECT organization_id || ':' || user_id AS id, * FROM public.memberships WHERE user_id = auth.user_id()"`,
    );
    expect(adopted.streams).toContain(
      'query: "SELECT id, name FROM public.organizations WHERE id IN (SELECT organization_id FROM public.memberships WHERE user_id = auth.user_id())"',
    );
    expect(adopted.publication).toContain(
      "create publication powersync for table public.memberships, public.organizations;",
    );
  });
});
