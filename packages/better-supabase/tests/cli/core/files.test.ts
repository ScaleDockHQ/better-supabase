/* oxlint-disable eslint/no-bitwise -- file permissions are the low 9 bits of `mode`. */

import { mkdtemp, readFile, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import type { FilePlan } from "../../../src/cli/core/files.ts";

import {
  applyPlan,
  changeLines,
  ownedByUs,
  planResult,
} from "../../../src/cli/core/files.ts";
import { readIfExists } from "../../../src/cli/core/io.ts";

const HEADER = "// Generated by better-supabase. Do not edit.\n";

async function project(files: Record<string, string> = {}): Promise<string> {
  const root = await mkdtemp(join(tmpdir(), "files-"));

  for (const [path, contents] of Object.entries(files)) {
    await writeFile(join(root, path), contents);
  }

  return root;
}

const plan = (root: string, files: FilePlan["files"]): FilePlan => ({
  root,
  files,
  regenerate: "cmd",
});

describe("applyPlan", () => {
  it("creates, updates and leaves equal files alone", async () => {
    const root = await project({ "same.txt": "x\r\n", "old.txt": "a\n" });

    const applied = await applyPlan(
      plan(root, [
        { path: "sub/new.txt", contents: "n\n" },
        { path: "same.txt", contents: "x\n" },
        { path: "old.txt", contents: "b\n", note: "users" },
      ]),
      {},
    );

    expect(changeLines(applied)).toEqual([
      "Created sub/new.txt",
      "Unchanged same.txt",
      "Updated old.txt (users)",
    ]);
    expect(await readFile(join(root, "sub/new.txt"), "utf-8")).toBe("n\n");
    expect(await readFile(join(root, "old.txt"), "utf-8")).toBe("b\n");
  });

  it("skips a file without the header unless --force is set", async () => {
    const root = await project({ "a.ts": "mine\n", "b.ts": "mine\n" });

    const files = [
      { path: "a.ts", contents: `${HEADER}x\n` },
      { path: "b.ts", contents: "y\n", policy: "create" as const },
    ];

    const skipped = await applyPlan(plan(root, files), {});

    expect(changeLines(skipped)).toEqual([
      "Skipped a.ts (not generated by better-supabase; pass --force to overwrite)",
      "Skipped b.ts (exists; pass --force to overwrite)",
    ]);
    expect(await readFile(join(root, "a.ts"), "utf-8")).toBe("mine\n");

    const forced = await applyPlan(plan(root, files), { force: true });

    expect(changeLines(forced)).toEqual(["Updated a.ts", "Updated b.ts"]);
  });

  it("writes nothing on --dry-run and prints the diff", async () => {
    const root = await project({ "a.txt": "x\n" });

    const applied = await applyPlan(
      plan(root, [{ path: "a.txt", contents: "y\n" }]),
      { "dry-run": true },
    );

    const result = planResult(plan(root, []), applied);

    expect(result.output?.split("\n")).toEqual([
      "--- a.txt\ton disk",
      "+++ a.txt\tgenerated",
      "@@ -1,1 +1,1 @@",
      "-x",
      "+y",
      "",
      "Would update a.txt",
    ]);
    expect(await readFile(join(root, "a.txt"), "utf-8")).toBe("x\n");
  });

  it("fails --check on drift and passes when up to date", async () => {
    const root = await project({ "a.txt": "x\n" });
    const stale = plan(root, [{ path: "a.txt", contents: "y\n" }]);

    expect(
      planResult(stale, await applyPlan(stale, { check: true })),
    ).toMatchObject({
      code: 1,
      error: "a.txt is out of date. Run `cmd`.",
      errorCode: "check_failed",
      data: { upToDate: false },
    });

    const fresh = plan(root, [{ path: "a.txt", contents: "x\n" }]);

    expect(
      planResult(fresh, await applyPlan(fresh, { check: true })),
    ).toMatchObject({ code: 0, output: "a.txt is up to date." });
  });

  it("hides the diff of a secret file and keeps its mode", async () => {
    const root = await project();

    const secret = plan(root, [
      { path: ".env", contents: "KEY=1\n", secret: true, mode: 0o600 },
    ]);

    const dry = await applyPlan(secret, { "dry-run": true });

    expect(dry.diffs).toEqual([
      ".env would change (the diff is hidden: the file holds secrets).",
    ]);

    await applyPlan(secret, {});

    expect((await stat(join(root, ".env"))).mode & 0o777).toBe(0o600);
  });

  it("removes stale files and refuses paths outside the root", async () => {
    const root = await project({ "gone.sql": "x\n" });

    const applied = await applyPlan(
      { ...plan(root, []), remove: ["gone.sql", "never.sql"] },
      {},
    );

    expect(changeLines(applied)).toEqual(["Removed gone.sql"]);
    expect(await readIfExists(join(root, "gone.sql"))).toBeUndefined();
    await expect(
      applyPlan(plan(root, [{ path: "../x.txt", contents: "" }]), {}),
    ).rejects.toMatchObject({ code: "outside_root" });
  });

  it("skips an edit target that is missing", async () => {
    const root = await project();

    const applied = await applyPlan(
      plan(root, [{ path: "config.ts", contents: "x", policy: "edit" }]),
      {},
    );

    expect(changeLines(applied)).toEqual(["Skipped config.ts (missing)"]);
  });

  it("reads the header from the first lines only", () => {
    expect(ownedByUs(HEADER)).toBe(true);
    expect(ownedByUs("a\nb\nc\nd\ne\n// generated by better-supabase")).toBe(
      false,
    );
  });
});
