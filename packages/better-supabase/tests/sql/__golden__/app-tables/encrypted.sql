create or replace function "better_supabase"."patients_reveal"(ids uuid[])
returns table (id uuid, "ssn" text, "email" text, "born_on" date, "diagnosis" text)
language plpgsql
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  v_service boolean := coalesce(nullif((select auth.jwt()) ->> 'role', ''), session_user::text) in ('service_role', 'postgres', 'supabase_admin');
  v_read record;
begin
  if (select auth.uid()) is null and not v_service then
    raise exception 'only signed-in users and the service role reveal patients' using errcode = '42501', hint = 'APP_REVEAL_FORBIDDEN';
  end if;
  if coalesce(cardinality(patients_reveal.ids), 0) > 500 then
    raise exception 'reveal at most 500 rows of patients per call' using errcode = '22023', hint = 'APP_REVEAL_TOO_MANY';
  end if;
  for v_read in
    select t."organization_id" as tenant, jsonb_agg(t.id order by t.id) as ids
    from "public"."patients" t
    where t.id = any (patients_reveal.ids) and (v_service or ("organization_id" in (select better_supabase.member_organization_ids())))
    group by 1
  loop
    perform better_supabase.audit_event(
    event_type => 'patient.viewed',
    category => 'read',
    target_type => 'patient',
    record_id => case when jsonb_array_length(v_read.ids) = 1 then v_read.ids ->> 0 end,
    summary => 'Revealed ' || jsonb_array_length(v_read.ids)::text || ' ' || 'patient' || ' record(s)',
    tenant => (v_read.tenant)::uuid,
    metadata => jsonb_build_object('ids', v_read.ids, 'columns', '["ssn","email","born_on","diagnosis"]'::jsonb)
  );
  end loop;
  return query
    with r as materialized (
      select t.id, 'tenant:' || (t."organization_id")::text as bsb_owner, t."ssn", t."email", t."born_on", t."diagnosis"
      from "public"."patients" t
      where t.id = any (patients_reveal.ids) and (v_service or ("organization_id" in (select better_supabase.member_organization_ids())))
    ),
    k as materialized (
      select o.bsb_owner, "better_supabase"."field_key"(o.bsb_owner, false) as bsb_key
      from (select distinct r.bsb_owner from r) o
    )
    select r.id, ("better_supabase"."field_open"(k.bsb_key, r."ssn"))::text, ("better_supabase"."field_open"(k.bsb_key, r."email"))::text, ("better_supabase"."field_open"(k.bsb_key, r."born_on"))::date, case when v_service then ("better_supabase"."field_open"(k.bsb_key, r."diagnosis"))::text end
    from r join k on k.bsb_owner = r.bsb_owner;
end;
$$;
