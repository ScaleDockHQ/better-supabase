import { describe, expect, it } from "vitest";

import { checkDesign } from "../../../src/create/index.ts";
import { importProject } from "../../../src/create/lite/index.ts";

const files = [
  {
    path: "supabase/migrations/001_init.sql",
    contents: `
      create table public.projects (
        id uuid primary key default gen_random_uuid(),
        owner_id uuid not null references auth.users (id) on delete cascade,
        name text not null,
        status text not null default 'open',
        budget numeric,
        created_at timestamptz not null default now(),
        updated_at timestamptz not null default now()
      );
      create index projects_name_idx on public.projects (name);
      alter table public.projects enable row level security;
      create policy own on public.projects for select to authenticated
        using (owner_id = auth.uid());

      create table public.tasks (
        id bigint generated by default as identity primary key,
        project_id uuid not null references public.projects (id),
        title text not null,
        tags text[] default '{}',
        mood interval
      );
      create table public.link (a uuid, b uuid, primary key (a, b));
      create table public.bsb_internal (id uuid primary key);
      create view public.open_projects as select * from public.projects;
      create function public.touch() returns trigger language plpgsql as $$ begin return new; end $$;
    `,
  },
];

describe("importProject", () => {
  it("reads migration files into a design and a report", async () => {
    const { design, report } = await importProject({
      source: { kind: "files", files },
    });

    expect(Object.keys(design.appTables ?? {}).toSorted()).toEqual([
      "projects",
      "tasks",
    ]);

    expect(design.appTables?.["projects"]).toMatchObject({
      scope: "none",
      indexes: [["name"]],
      columns: {
        owner_id: {
          type: "uuid",
          nullable: false,
          references: { table: "auth.users", onDelete: "cascade" },
        },
        name: { type: "text", nullable: false },
        status: { type: "text", nullable: false, default: "'open'" },
        budget: { type: "numeric" },
      },
    });

    expect(design.appTables?.["projects"]?.columns).not.toHaveProperty("id");
    expect(design.appTables?.["projects"]?.timestamps).toBeUndefined();

    expect(design.appTables?.["tasks"]).toMatchObject({
      id: "bigint",
      timestamps: false,
      columns: {
        project_id: { references: { table: "projects" } },
        tags: { type: "text[]", default: "'{}'" },
      },
    });

    expect(report.blockOwned).toEqual(["public.bsb_internal"]);
    expect(report.counts).toMatchObject({
      tables: 3,
      modeledTables: 2,
      views: 1,
    });

    expect(report.preserved.map((each) => `${each.kind}:${each.name}`)).toEqual(
      expect.arrayContaining([
        "table:public.link",
        "view:public.open_projects",
      ]),
    );

    expect(report.tables.find((each) => each.name === "projects")?.rung).toBe(
      "protected",
    );
    expect(report.tables.find((each) => each.name === "tasks")?.rung).toBe(
      "open",
    );

    expect(report.issues.map((each) => `${each.code}:${each.table}`)).toContain(
      "verify_rls_disabled:tasks",
    );
  }, 60_000);

  it("produces a design the checker accepts", async () => {
    const { design } = await importProject({
      source: { kind: "files", files },
    });

    expect((await checkDesign({ ...design, preset: "saas" }, "saas")).ok).toBe(
      true,
    );
  }, 60_000);

  it("reports SQL errors from the files and keeps going", async () => {
    const { report } = await importProject({
      source: {
        kind: "files",
        files: [
          { path: "a.sql", contents: "create table nope (" },
          {
            path: "b.sql",
            contents: "create table public.ok (id uuid primary key);",
          },
        ],
      },
    });

    expect(report.issues[0]).toMatchObject({
      code: "sql_error",
      file: "a.sql",
    });
    expect(report.counts.modeledTables).toBe(1);
  }, 60_000);

  it("reads a project through the Management API", async () => {
    const requests: { url: string; auth: string | null }[] = [];

    const catalog = {
      tables: [
        {
          schema: "public",
          name: "notes",
          kind: "r",
          rls: true,
          comment: null,
          columns: [
            {
              name: "id",
              type: "uuid",
              nullable: false,
              default: "gen_random_uuid()",
              identity: null,
              generated: false,
              comment: null,
            },
            {
              name: "body",
              type: "text",
              nullable: true,
              default: null,
              identity: null,
              generated: false,
              comment: null,
            },
          ],
          constraints: [
            {
              type: "p",
              columns: ["id"],
              refSchema: null,
              refTable: null,
              refColumns: null,
              onDelete: null,
            },
          ],
          indexes: [],
          policies: 0,
          triggers: 0,
        },
      ],
      functions: [],
    };

    const { design, report } = await importProject({
      source: {
        kind: "supabase",
        projectRef: "abc",
        accessToken: "tok",
        fetch: (input, init) => {
          requests.push({
            url: String(input),
            auth: new Headers(init?.headers).get("authorization"),
          });

          return Promise.resolve(
            Response.json([{ catalog: JSON.stringify(catalog) }]),
          );
        },
      },
    });

    expect(requests).toEqual([
      {
        url: "https://api.supabase.com/v1/projects/abc/database/query/read-only",
        auth: "Bearer tok",
      },
    ]);

    expect(design.appTables?.["notes"]?.columns).toEqual({
      body: { type: "text" },
    });
    expect(report.issues.map((each) => each.code)).toEqual([
      "verify_no_policies",
    ]);
  });

  it("rejects a failing Management API call", async () => {
    await expect(
      importProject({
        source: {
          kind: "supabase",
          projectRef: "abc",
          accessToken: "bad",
          fetch: () => Promise.resolve(new Response("no", { status: 401 })),
        },
      }),
    ).rejects.toThrow("401");
  });
});
