import type { DoctorContext, FindingInput, Rule, TextFile } from "./rules.ts";

import { withoutComments } from "../schema-reader/index.ts";
import { declarativeSchemasDir, tomlGet } from "../supabase-config.ts";
import { CATALOG, DO_BLOCK, EXECUTES, lineAt, pgdeltaToml } from "./pgdelta.ts";

const DDL = /\b(create|alter|drop|grant|revoke|comment\s+on)\b/i;

/** `cron.schedule` called inside a function or `do` body, not at the top. */
const CRON_IN_BODY =
  /\$(\w*)\$[\s\S]*?(?<!['"(])\bcron\.schedule(?:_in_database)?\s*\(/gi;

/**
 * The body checks that pg_cron is installed before it schedules: the job is
 * optional, so a plain statement would make the extension mandatory.
 */
const CRON_GUARD =
  /to_regnamespace\s*\(\s*'cron'|to_regprocedure\s*\(\s*'cron\./i;

const PUBLICATION_EXECUTE =
  /\bexecute\b[^;]*?\balter\s+publication\b|\balter\s+publication\b[^;]*\bformat\s*\(/gi;

const DEFAULT_PRIVILEGES = /\balter\s+default\s+privileges\b([^;]*);/gi;

const MODULE_FILE = /^-- @(?:bsb-block|bs-module)(?:-data)? ([a-zA-Z0-9-]+)/m;

/** The module that wrote a generated file, if one did. */
const generatedBy = (file: TextFile): string | undefined =>
  MODULE_FILE.exec(file.text)?.[1];

/** Every file of the declarative tree, the generated module files included. */
function pgdeltaTreeFiles(context: DoctorContext): readonly TextFile[] {
  const toml = pgdeltaToml(context);

  if (toml === undefined) {
    return [];
  }

  const root = `${declarativeSchemasDir(toml, "pg-delta")}/`;

  return (context.sqlFiles ?? []).filter(
    (file) => file.path.startsWith(root) && !isCustom(file.path, root),
  );
}

/**
 * Statements pg-delta has no way to see or order, in the project's own
 * declarative schema files: it records objects by reading the database the
 * files load into, so what a `do` block, a function body or `execute` does
 * later is invisible to it.
 */
function unsafeStatements(context: DoctorContext): FindingInput[] {
  return pgdeltaTreeFiles(context).flatMap((file) => {
    const text = withoutComments(file.text);
    const found: FindingInput[] = [];
    const owner = generatedBy(file);

    const label =
      owner === undefined
        ? file.path
        : `${file.path} (written by better-supabase, module ${owner})`;

    const note =
      owner === undefined
        ? ""
        : " Upgrade better-supabase and regenerate; do not edit this file.";

    const at = (index: number): { file: string; line: number } => ({
      file: file.path,
      line: lineAt(text, index),
    });

    for (const match of text.matchAll(DO_BLOCK)) {
      const body = match[2]!;

      // Catalog loops are BS318.
      if (CATALOG.test(body) && EXECUTES.test(body)) {
        continue;
      }

      if (DDL.test(body)) {
        found.push({
          message: `${label} has a do block that runs DDL. pg-delta runs it with no dependency position and never sees what it creates, so the diff can drop it or plan it twice. Write the statements as plain SQL, with \`create ... if not exists\` where a rerun must be safe.`,
          target: file.path,
          location: at(match.index),
        });
      }
    }

    for (const match of text.matchAll(CRON_IN_BODY)) {
      // The last delimiter before the call opens the body that holds it.
      const opener = match[0].lastIndexOf(`$${match[1]}$`);

      if (CRON_GUARD.test(match[0].slice(Math.max(opener, 0)))) {
        continue;
      }

      found.push({
        message: `${label} calls cron.schedule inside a function or do block. pg-delta reads pg_cron jobs from the catalog by name, so a job scheduled at run time is not part of the schema. Schedule it at the top level: select cron.schedule('name', '10 seconds', 'select ...');${note}`,
        target: file.path,
        location: at(match.index),
      });
    }

    for (const match of text.matchAll(PUBLICATION_EXECUTE)) {
      found.push({
        message: `${label} changes a publication through execute or format. pg-delta reads publication membership from the catalog and cannot order a statement it only sees as text. Write \`alter publication supabase_realtime add table <table>;\` for each table.`,
        target: file.path,
        location: at(match.index),
      });
    }

    for (const match of text.matchAll(DEFAULT_PRIVILEGES)) {
      if (!/\bfor\s+(role|user)\b/i.test(match[1]!)) {
        found.push({
          message: `${label} has alter default privileges without \`for role\`. It applies to the role that loads the file, which is a different role in the shadow database than the one that owns your objects, so the diff gets default privileges for the wrong owner. Name it: alter default privileges for role postgres in schema ...`,
          target: file.path,
          location: at(match.index),
        });
      }
    }

    return found;
  });
}

/**
 * The root directories pg-delta reserves in a declarative tree, and the schema
 * names that would collide with them.
 */
const RESERVED = /^_(cluster|custom)$/i;

function reservedNames(context: DoctorContext): FindingInput[] {
  const toml = pgdeltaToml(context);

  if (toml === undefined) {
    return [];
  }

  const root = `${declarativeSchemasDir(toml, "pg-delta")}/`;
  const found: FindingInput[] = [];

  for (const file of context.sqlFiles ?? []) {
    if (!file.path.startsWith(root)) {
      continue;
    }

    const [first] = file.path.slice(root.length).split("/");

    if (
      first !== undefined &&
      /^_cluster$/i.test(first) &&
      first !== "_cluster"
    ) {
      found.push({
        message: `${file.path} sits in a folder that differs from the reserved \`_cluster\` only in case. pg-delta owns \`_cluster/\` and \`_custom/\` at the root of the tree, and a case variant folds into them on some file systems. Rename the folder.`,
        target: file.path,
        location: { file: file.path, line: 1 },
      });
    }

    const text = withoutComments(file.text);

    for (const match of text.matchAll(
      /\bcreate\s+schema\s+(?:if\s+not\s+exists\s+)?("?)([\w$]+)\1/gi,
    )) {
      if (RESERVED.test(match[2]!)) {
        found.push({
          message: `${file.path} creates a schema named ${match[2]}. pg-delta reserves \`_cluster\` and \`_custom\` as the root folders of a declarative tree, and a schema of that name would write into them. Pick another schema name.`,
          target: file.path,
          location: { file: file.path, line: lineAt(text, match.index) },
        });
      }
    }
  }

  return found;
}

function schemaPathsUnderPgDelta(context: DoctorContext): FindingInput[] {
  const toml = context.configToml;

  if (
    toml === undefined ||
    tomlGet(toml.document, ["experimental", "pgdelta", "enabled"]) !== true
  ) {
    return [];
  }

  const paths = tomlGet(toml.document, ["db", "migrations", "schema_paths"]);

  if (!Array.isArray(paths) || paths.length === 0) {
    return [];
  }

  return [
    {
      message: `${toml.path} sets \`[db.migrations] schema_paths\` and enables pg-delta. pg-delta loads every file under \`${toml.dir}/schemas\` and ignores the list, so the order you wrote is not the order that runs, and a file you left out is still loaded. Remove \`schema_paths\` and let pg-delta order the files.`,
      target: toml.path,
      location: { file: toml.path, line: 1 },
    },
  ];
}

const isCustom = (path: string, root: string): boolean =>
  path.startsWith(`${root}_custom/`);

const DIRECTIVE = /^\s*--\s*pgdelta-migration:\s*(.+?)\s*$/gm;

/** `_custom/` files and what they declare about their migration. */
function customFiles(context: DoctorContext): FindingInput[] {
  const toml = pgdeltaToml(context);

  if (toml === undefined) {
    return [];
  }

  const root = `${declarativeSchemasDir(toml, "pg-delta")}/`;
  const files = context.sqlFiles ?? [];
  const paths = new Set(files.map((file) => file.path));
  const found: FindingInput[] = [];

  for (const file of files.filter((candidate) =>
    isCustom(candidate.path, root),
  )) {
    const directives = [...file.text.matchAll(DIRECTIVE)].map(
      (match) => match[1]!,
    );

    if (directives.length === 0) {
      found.push({
        message: `${file.path} has no \`-- pgdelta-migration:\` line. pg-delta loads \`_custom/\` files into the shadow only and never runs them on your database, so the change has to ship in a migration. Add \`-- pgdelta-migration: ../../migrations/<file>.sql\` at the top of the file, or \`-- pgdelta-migration: none\` when it has no migration.`,
        target: file.path,
        location: { file: file.path, line: 1 },
      });
    }

    for (const directive of directives.filter((value) => value !== "none")) {
      const resolved = new URL(
        directive,
        `file:///${file.path.slice(0, file.path.lastIndexOf("/") + 1)}`,
      ).pathname.slice(1);

      if (!paths.has(resolved)) {
        found.push({
          message: `${file.path} names the migration ${directive}, and ${resolved} does not exist. Fix the path, or write the migration.`,
          target: file.path,
          location: { file: file.path, line: 1 },
        });
      }
    }
  }

  return found;
}

const MODELED_DDL =
  /^\s*create\s+(?:or\s+replace\s+)?(?:unlogged\s+)?(?:temp(?:orary)?\s+)?(?:table|view|materialized\s+view|function|procedure|trigger|policy|index|unique\s+index|sequence|schema|type|domain)\b/gim;

/**
 * Modeled objects belong in the managed tree, so `_custom/` keeps only what
 * pg-delta does not model.
 */
function modeledInCustom(context: DoctorContext): FindingInput[] {
  const toml = pgdeltaToml(context);

  if (toml === undefined) {
    return [];
  }

  const root = `${declarativeSchemasDir(toml, "pg-delta")}/`;

  return (context.sqlFiles ?? [])
    .filter((file) => isCustom(file.path, root))
    .flatMap((file) => {
      const text = withoutComments(file.text);
      const match = MODELED_DDL.exec(text);

      MODELED_DDL.lastIndex = 0;

      return match === null
        ? []
        : [
            {
              message: `${file.path} creates an object pg-delta models (${match[0].trim().toLowerCase()}). \`_custom/\` is for what it does not model (casts, operators, text search objects, statistics, transforms) plus idempotent data. A modeled object kept here appears twice in the shadow once the managed tree has it. Move it next to its table.`,
              target: file.path,
              location: { file: file.path, line: lineAt(text, match.index) },
            },
          ];
    });
}

const PUBLICATION =
  /\b(?:create\s+publication\s+("?)([\w$]+)\1\s+for\s+table\s+([^;]+?)|alter\s+publication\s+("?)([\w$]+)\4\s+add\s+table\s+([^;]+?))\s*(?:with\b[^;]*)?;/gi;

const tableName = (raw: string): string =>
  raw
    .trim()
    .replaceAll('"', "")
    .replace(/^only\s+/i, "")
    .replace(/\s+.*$/s, "")
    .toLowerCase();

/**
 * Tables a publication other than `supabase_realtime` lists. A Pipelines
 * (replication) source needs a primary key or `replica identity full` on each,
 * or Postgres refuses their updates and deletes.
 */
function pipelinesReadiness(context: DoctorContext): FindingInput[] {
  const toml = pgdeltaToml(context);
  const files = context.sqlFiles ?? [];

  if (toml === undefined) {
    return [];
  }

  const root = `${declarativeSchemasDir(toml, "pg-delta")}/`;
  const texts = files.filter((file) => file.path.startsWith(root));

  const keyed = new Set<string>();
  const tables = new Map<string, { file: string; index: number }>();

  for (const file of texts) {
    const text = withoutComments(file.text);

    for (const match of text.matchAll(
      /\bcreate\s+table\s+(?:if\s+not\s+exists\s+)?([\w."$]+)\s*\(([\s\S]*?)\)\s*(?:partition|inherits|with|tablespace|;)/gi,
    )) {
      const name = tableName(match[1]!);
      const qualified = name.includes(".") ? name : `public.${name}`;

      tables.set(qualified, { file: file.path, index: match.index });

      if (/\bprimary\s+key\b/i.test(match[2]!)) {
        keyed.add(qualified);
      }
    }

    for (const match of text.matchAll(
      /\balter\s+table\s+(?:only\s+)?(?:if\s+exists\s+)?([\w."$]+)\s+(?:add\s+(?:constraint\s+\S+\s+)?primary\s+key|replica\s+identity\s+full)/gi,
    )) {
      const name = tableName(match[1]!);

      keyed.add(name.includes(".") ? name : `public.${name}`);
    }
  }

  const found: FindingInput[] = [];

  for (const file of texts) {
    const text = withoutComments(file.text);

    for (const match of text.matchAll(PUBLICATION)) {
      const publication = (match[2] ?? match[5] ?? "").toLowerCase();

      if (publication === "supabase_realtime") {
        continue;
      }

      for (const raw of (match[3] ?? match[6] ?? "").split(",")) {
        const name = tableName(raw);
        const qualified = name.includes(".") ? name : `public.${name}`;

        if (tables.has(qualified) && !keyed.has(qualified)) {
          found.push({
            message: `${file.path} publishes ${qualified} in ${publication}, and the table has no primary key or \`replica identity full\`. A Pipeline (replication) source cannot replicate updates and deletes of such a table, and Postgres refuses them once the publication includes it. Add a primary key.`,
            target: file.path,
            location: { file: file.path, line: lineAt(text, match.index) },
          });
        }
      }
    }
  }

  return found;
}

