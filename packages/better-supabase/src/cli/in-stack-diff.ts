/**
 * Schemas the platform owns. The declarative files may add policies to
 * their tables (`storage.objects`), so those policies are dropped and
 * replayed, but the schemas themselves are kept.
 */
const PLATFORM_SCHEMAS: ReadonlySet<string> = new Set([
  "_analytics",
  "_realtime",
  "auth",
  "cron",
  "extensions",
  "graphql",
  "graphql_public",
  "information_schema",
  "net",
  "pgbouncer",
  "pgmq",
  "pgsodium",
  "pgsodium_masks",
  "pgtle",
  "realtime",
  "repack",
  "storage",
  "supabase_functions",
  "supabase_migrations",
  "tiger",
  "tiger_data",
  "topology",
  "vault",
]);

/** The local stack's superuser; pg-delta skips objects it owns. */
const ADMIN_ROLE = "supabase_admin";

/** Why the Supabase CLI could not start its shadow database. */
const SHADOW_FAILURE =
  /could not create shared memory segment|No space left on device|shmget|shadow database/i;

export function isShadowFailure(output: string): boolean {
  return SHADOW_FAILURE.test(output);
}

/** The same database as `supabase_admin`, which may create databases and read every schema. */
export function adminUrl(url: string): string {
  const parsed = new URL(url);
  parsed.username = ADMIN_ROLE;

  return parsed.toString();
}

export function withDatabase(url: string, database: string): string {
  const parsed = new URL(url);
  parsed.pathname = `/${database}`;

  return parsed.toString();
}

/** The migration versions (`<digits>_name.sql`) the stack has not applied. */
export function pendingMigrations(
  files: readonly string[],
  applied: ReadonlySet<string>,
): readonly string[] {
  return files.filter((file) => {
    const version = /^(\d+)_/.exec(basename(file))?.[1];

    return version !== undefined && !applied.has(version);
  });
}

/** The SQL from `supabase db diff --output-format json`, or its text output. */
export function diffSql(stdout: string): string {
  const start = stdout.indexOf("{");

  if (start !== -1) {
    try {
      const parsed: unknown = JSON.parse(stdout.slice(start));

      if (
        typeof parsed === "object" &&
        parsed !== null &&
        "diff" in parsed &&
        typeof parsed.diff === "string"
      ) {
        return parsed.diff;
      }
    } catch {
      // Text output: the SQL itself.
    }
  }

  return stdout;
}

/** The postmaster's `bin` directory, from `ps` lines and its data directory. */
export function postgresBin(
  psOutput: string,
  dataDirectory: string,
): string | undefined {
  for (const line of psOutput.split("\n")) {
    const command = line.trim().replace(/^\d+\s+/, "");
    const executable = command.split(/\s+/)[0];

    if (
      executable !== undefined &&
      basename(executable).includes("postgres") &&
      command.includes(` -D ${dataDirectory}`)
    ) {
      return dirname(executable);
    }
  }

  return undefined;
}

