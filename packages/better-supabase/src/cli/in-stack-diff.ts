/** UTC `YYYYMMDDHHMMSS`, the Supabase CLI's migration version. */
export function migrationVersion(now: Date): string {
  return now.toISOString().replaceAll(/[-:T]/g, "").slice(0, 14);
}

export type PgDelta = typeof PgDeltaModule;

/** The minimal `pg` surface the planner needs: pools it can end. */
interface PoolModule {
  Pool: new (options: { connectionString: string }) => PoolHandle;
}

type PoolHandle = Pool;

export interface InStackDiffOptions {
  /** The local stack's connection string. */
  readonly url: string;
  readonly root: string;
  readonly env: CliEnv;
  /** Declarative schema files, relative to the root, in the order to try them. */
  readonly files: readonly string[];
  /** The folder they live in, relative to the root (`supabase/schemas`). */
  readonly schemasDir: string;
  /** The migration files, relative to the root, to check the stack has applied. */
  readonly migrations: readonly string[];
  /** Let destructive actions through (`--allow-data-loss`). */
  readonly allowDataLoss?: boolean;
  /** Renames recorded as `-- bsb: rename old -> new`. */
  readonly hints?: readonly RenameHint[];
  readonly open?: typeof connect;
  /** Loads pg-delta; tests pass a fake. */
  readonly loadDelta?: () => Promise<PgDelta>;
  /** Opens a pool for pg-delta; tests pass a fake. */
  readonly openPool?: (url: string) => Promise<PoolHandle>;
  readonly log?: (line: string) => void;
}

export interface InStackDiffResult {
  /** The migration SQL, empty when nothing changed or the gate blocked it. */
  readonly sql: string;
  readonly gate: PlanGate;
  /** The gate's findings, as `Issue`s with `source: "plan"`. */
  readonly issues: readonly Issue[];
  /** What pg-delta reported while it loaded and read the databases. */
  readonly diagnostics: readonly Diagnostic[];
  /** Statements pg-delta left out of the plan, with their files. */
  readonly skipped: readonly { readonly file: string; readonly stmt: string }[];
}

/**
 * Pg-delta is an optional peer (with `@supabase/pg-topo`) that only `db diff`
 * needs, so it loads on demand. Without it, `db diff` says how to install it.
 */
export async function loadPgDelta(
  load: () => Promise<PgDelta> = () => import("@supabase/pg-delta"),
): Promise<PgDelta> {
  try {
    return await load();
  } catch {
    throw new CliError(
      "dependency_missing",
      'better-supabase needs "@supabase/pg-delta" and "@supabase/pg-topo" to plan the diff. Install them: pnpm add -D @supabase/pg-delta @supabase/pg-topo',
      { suggestion: "pnpm add -D @supabase/pg-delta @supabase/pg-topo" },
    );
  }
}

/**
 * `pg` is an optional peer that pg-delta shares; the pools it takes come from
 * it.
 */
export async function openPgPool(url: string): Promise<PoolHandle> {
  try {
    const mod: { default?: PoolModule } & PoolModule = await import("pg");

    const { Pool } = mod.default ?? mod;

    return new Pool({ connectionString: url });
  } catch {
    throw new CliError(
      "dependency_missing",
      'better-supabase needs the "pg" package to diff the schema. Install it: pnpm add -D pg',
      { suggestion: "pnpm add -D pg" },
    );
  }
}

async function appliedVersions(client: PgQueryable): Promise<Set<string>> {
  const rows = await client
    .query<{ version: string }>(
      "select version from supabase_migrations.schema_migrations",
    )
    .then((result) => result.rows)
    .catch(() => []);

  return new Set(rows.map((row) => row.version));
}

function behindMessage(behind: readonly string[]): string {
  return `The stack has not applied ${String(behind.length)} migration(s) (${behind.slice(0, 3).join(", ")}${behind.length > 3 ? ", ..." : ""}), so the diff would repeat them. Run supabase migration up, then diff again.`;
}

/** One SQL statement per action, each ended with a semicolon. */
function actionsSql(actions: readonly { readonly sql: string }[]): string {
  return actions
    .map((action) => {
      const sql = action.sql.trim();

      return sql.endsWith(";") ? sql : `${sql};`;
    })
    .join("\n\n");
}

/**
 * Diffs the declarative schema against the running stack with pg-delta's
 * library plan, connected as the stack's `postgres` role: objects owned by
 * `supabase_admin` are invisible to pg-delta, so a shadow that role created
 * would look empty. The plan: it creates a shadow database on the stack's
 * cluster, loads the files into it, and plans the changes from the stack to the
 * shadow. Renames are applied only when a hint confirms them, and destructive
 * actions are blocked unless `allowDataLoss` is set. The shadow is always
 * dropped.
 */
export async function inStackDiff(
  options: InStackDiffOptions,
): Promise<InStackDiffResult> {
  const open = options.open ?? connect;
  const loadDelta = options.loadDelta ?? loadPgDelta;
  const openPool = options.openPool ?? openPgPool;
  const log = options.log ?? (() => {});
  const main = await open(options.url);

  try {
    const behind = pendingMigrations(
      options.migrations,
      await appliedVersions(main.client),
    );

    if (behind.length > 0) {
      throw new CliError("check_failed", behindMessage(behind), {
        suggestion: "supabase migration up",
      });
    }
  } finally {
    await main.close();
  }

  const delta = await loadDelta();
  const hints = options.hints ?? [];

  const files = await Promise.all(
    options.files.map(async (file) => ({
      name: file,
      sql: await readFile(join(options.root, file), "utf-8"),
    })),
  );

  log("Creating a shadow database on the stack");

  const shadow = await delta
    .provisionCoLocatedShadow(options.url)
    .catch((cause: unknown) => {
      throw new CliError(
        "failed",
        cause instanceof Error ? cause.message : String(cause),
      );
    });

  const target = await openPool(options.url);
  const scratch = await openPool(shadow.url);

  try {
    const planFiles = (
      accept: NonNullable<PlanSchemaFilesOptions["acceptRenames"]>,
    ): ReturnType<PgDelta["planSchemaFiles"]> =>
      delta.planSchemaFiles(target, scratch, files, {
        profile: delta.supabaseProfile,
        renames: "prompt",
        seedAssumedSchemas: true,
        acceptRenames: accept,
      });

    log(`Planning ${String(files.length)} schema file(s) with pg-delta`);

    let result = await planFiles([]);

    let gate = gatePlan(describePlan(delta, result.plan), {
      hints,
      allowDataLoss: options.allowDataLoss === true,
    });

    if (gate.accepted.length > 0) {
      const pairs = result.plan.renameCandidates.filter((candidate) =>
        gate.accepted.some(
          (accepted) =>
            accepted.from === delta.encodeId(candidate.from) &&
            accepted.to === delta.encodeId(candidate.to),
        ),
      );

      result = await planFiles(pairs);
      gate = gatePlan(describePlan(delta, result.plan), {
        hints,
        allowDataLoss: options.allowDataLoss === true,
      });
    }

    const sql = gate.blocked ? "" : actionsSql(result.plan.actions);

    const diagnostics = [
      ...result.loadDiagnostics,
      ...result.targetDiagnostics,
      ...result.driftDiagnostics,
    ];

    return {
      sql,
      gate,
      issues: gate.issues,
      diagnostics,
      skipped: result.skipped,
    };
  } finally {
    await Promise.allSettled([target.end(), scratch.end()]);
    await shadow.cleanup();
  }
}

/** The plan with stable ids written as strings, the shape `gatePlan` reads. */
function describePlan(
  delta: Pick<PgDelta, "encodeId">,
  plan: Awaited<ReturnType<PgDelta["planSchemaFiles"]>>["plan"],
): Parameters<typeof gatePlan>[0] {
  return {
    actions: plan.actions,
    renameCandidates: plan.renameCandidates.map((candidate) => ({
      kind: candidate.kind,
      from: delta.encodeId(candidate.from),
      to: delta.encodeId(candidate.to),
      status: candidate.status,
      ...(candidate.reason === undefined ? {} : { reason: candidate.reason }),
    })),
  };
}

/** The migration files under `supabase/migrations`, relative to the root. */
export async function migrationFiles(
  root: string,
  supabaseDir: string,
): Promise<readonly string[]> {
  const dir = join(supabaseDir, "migrations");
  const names = await readdir(join(root, dir)).catch(() => []);

  return names
    .filter((name) => name.endsWith(".sql"))
    .toSorted()
    .map((name) => join(dir, name));
}
