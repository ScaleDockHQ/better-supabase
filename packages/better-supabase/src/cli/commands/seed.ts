import { existsSync } from "node:fs";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";

import type { ResolvedConfig } from "../../config/index.ts";
import type { AnyCommand, CliArgs, CliOptions } from "../core/command.ts";
import type { CommandResult } from "../core/io.ts";
import type { CliEnv } from "../env.ts";

import { isSeed } from "../../testing/index.ts";
import { databaseUrl, importExport, stdinDatabaseUrl } from "../config.ts";
import { defineCliCommand } from "../core/command.ts";
import {
  applyPlan,
  hasConflicts,
  changeLines,
  type FilePlan,
  insideRoot,
  PLAN_ARGS,
  planResult,
} from "../core/files.ts";
import { display } from "../core/io.ts";
import { commandMeta } from "../core/manifest.ts";
import { connect } from "../db.ts";
import { supabaseDir } from "../supabase-toml.ts";
import { DB_URL_STDIN_ARG } from "./source-args.ts";

const ARGS = {
  apply: {
    type: "boolean",
    description:
      "Also insert the rows into the database ($DATABASE_URL, $SUPABASE_DB_URL, --db-url-stdin, or the local stack)",
  },
  entry: {
    type: "string",
    description: "Defaults to seed.entry (supabase/seed.ts)",
    valueHint: "file",
  },
  out: {
    type: "string",
    description:
      "Defaults to seed.output (supabase/seeds/000_better_supabase.sql)",
    valueHint: "file",
  },
} as const;

export type SeedArgs = CliArgs<
  typeof ARGS & typeof DB_URL_STDIN_ARG & typeof PLAN_ARGS
>;

export type SeedFlags = CliOptions<
  typeof ARGS & typeof DB_URL_STDIN_ARG & typeof PLAN_ARGS
>;

const HEADER = "-- Generated by `better-supabase seed`";

export async function runSeed(
  config: ResolvedConfig,
  args: SeedFlags,
  env: CliEnv,
  open: typeof connect = connect,
  dbUrl?: string,
): Promise<CommandResult> {
  const entry = args.entry ?? config.seed.entry;
  const out = args.out ?? config.seed.output;
  const seed = await importExport(resolve(config.root, entry), "seed");

  if (!isSeed(seed)) {
    return {
      code: 1,
      errorCode: "invalid_input",
      error: `${display(config.root, entry)} must export defineSeed(...) as \`seed\` or default.`,
    };
  }

  const statements = seed.statements();
  const contents = `${HEADER} from ${display(config.root, entry)}. Do not edit.\n\n${statements.join("\n\n")}\n`;

  const plan: FilePlan = {
    root: config.root,
    regenerate: "better-supabase seed",
    files: [
      {
        path: insideRoot(config.root, out, "--out"),
        contents,
        policy: "owned",
        note: `${statements.length} table${statements.length === 1 ? "" : "s"}`,
      },
    ],
  };

  const applied = await applyPlan(plan, args);
  const file = display(config.root, out);

  if (applied.mode !== "write" || hasConflicts(applied)) {
    return planResult(plan, applied, { data: { file } });
  }

  const lines = changeLines(applied);

  if (args.apply === true) {
    const { client, close } = await open(await databaseUrl(config, env, dbUrl));

    try {
      await client.query("begin");

      for (const text of statements) {
        await client.query(text);
      }

      await client.query("commit");
    } catch (error) {
      await client.query("rollback");
      throw error;
    } finally {
      await close();
    }

    lines.push("Inserted the fixtures (existing rows were kept).");
  }

  const dir = supabaseDir(config.root);
  let listed = true;
  const toml = resolve(config.root, dir, "config.toml");

  const seedPath = out.startsWith(`${dir}/`)
    ? `./${out.slice(dir.length + 1)}`
    : out;

  if (existsSync(toml)) {
    const text = await readFile(toml, "utf-8");
    const folder = seedPath.replace(/[^/]+$/, "");

    if (!text.includes(seedPath) && !text.includes(`${folder}*`)) {
      listed = false;
      lines.push(
        "",
        `Add it to ${dir}/config.toml so \`supabase db reset\` runs it:`,
        "  [db.seed]",
        `  sql_paths = ["./seed.sql", "${seedPath}"]`,
      );
    }
  }

  return {
    code: 0,
    output: lines.join("\n"),
    data: {
      file,
      files: applied.changes,
      tables: statements.length,
      applied: args.apply === true,
      listed,
    },
  };
}

export const seedCommand: AnyCommand = defineCliCommand({
  meta: commandMeta("seed"),
  args: { ...ARGS, ...DB_URL_STDIN_ARG, ...PLAN_ARGS },
  run: async (args, { config, env, io, log }) => {
    const dbUrl = await stdinDatabaseUrl(args["db-url-stdin"], io);

    const seed = (): Promise<CommandResult> =>
      runSeed(config, args, env, connect, dbUrl);

    return args.apply === true
      ? log.progress("Inserting the seed rows", seed)
      : seed();
  },
});
