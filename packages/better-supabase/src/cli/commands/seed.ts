const ARGS = {
  apply: {
    type: "boolean",
    description:
      "Also insert the rows into the database ($DATABASE_URL, $SUPABASE_DB_URL, --db-url-stdin, or the local stack)",
  },
  entry: {
    type: "string",
    description: "Defaults to database.seed.entry (supabase/seed.ts)",
    valueHint: "file",
  },
  out: {
    type: "string",
    description:
      "Defaults to database.seed.output (supabase/seeds/000_better_supabase.sql)",
    valueHint: "file",
  },
  tenant: {
    type: "string",
    description:
      "Insert database.seed.perTenant (supabase/seed.tenant.ts) for this organization slug or id, or '*' for every organization",
    valueHint: "slug",
  },
} as const;

export type SeedArgs = CliArgs<
  typeof ARGS & typeof DB_URL_STDIN_ARG & typeof STACK_ARG & typeof PLAN_ARGS
>;

export type SeedFlags = CliOptions<
  typeof ARGS & typeof DB_URL_STDIN_ARG & typeof STACK_ARG & typeof PLAN_ARGS
>;

const HEADER = "-- Generated by `better-supabase db seed`";

export async function runSeed(
  config: ResolvedConfig,
  args: SeedFlags,
  env: CliEnv,
  open: typeof connect = connect,
  dbUrl?: string,
  requireConsent: (request: ConsentRequest) => void = () => {},
): Promise<CommandResult> {
  if (args.tenant !== undefined) {
    return runTenantSeed(config, args, env, open, dbUrl, requireConsent);
  }

  const entry = args.entry ?? config.seed.entry;
  const out = args.out ?? config.seed.output;
  const seed = await importExport(resolve(config.root, entry), "seed");

  if (!isSeed(seed)) {
    return {
      code: 1,
      errorCode: "invalid_input",
      error: `${display(config.root, entry)} must export defineSeed(...) as \`seed\` or default.`,
    };
  }

  const statements = seed.statements();
  const contents = `${HEADER} from ${display(config.root, entry)}. Do not edit.\n\n${statements.join("\n\n")}\n`;

  const plan: FilePlan = {
    root: config.root,
    regenerate: "better-supabase db seed",
    files: [
      {
        path: insideRoot(config.root, out, "--out"),
        contents,
        policy: "owned",
        note: `${statements.length} table${statements.length === 1 ? "" : "s"}`,
      },
    ],
  };

  const inserts =
    args.apply === true && args["dry-run"] !== true && args.check !== true;

  const url = inserts
    ? await databaseUrl(config, env, dbUrl, args.stack ?? env.BSB_STACK)
    : undefined;

  if (url !== undefined && !isLocalDatabaseUrl(url)) {
    requireConsent({
      effect: "database-write",
      detail: `seed --apply inserts rows into ${databaseHost(url)}`,
    });
  }

  const applied = await applyPlan(plan, args);
  const file = display(config.root, out);

  if (applied.mode !== "write" || hasConflicts(applied)) {
    return planResult(plan, applied, { data: { file } });
  }

  const lines = changeLines(applied);

  if (url !== undefined) {
    const { client, close } = await open(url);

    try {
      await client.query("begin");

      for (const text of statements) {
        await client.query(text);
      }

      await client.query("commit");
    } catch (error) {
      await client.query("rollback");
      throw error;
    } finally {
      await close();
    }

    lines.push("Inserted the fixtures (existing rows were kept).");
  }

  const dir = supabaseDir(config.root);
  let listed = true;
  const toml = resolve(config.root, dir, "config.toml");

  const seedPath = out.startsWith(`${dir}/`)
    ? `./${out.slice(dir.length + 1)}`
    : out;

  if (existsSync(toml)) {
    const text = await readFile(toml, "utf-8");
    const folder = seedPath.replace(/[^/]+$/, "");

    if (!text.includes(seedPath) && !text.includes(`${folder}*`)) {
      listed = false;
      lines.push(
        "",
        `Add it to ${dir}/config.toml so \`supabase db reset\` runs it:`,
        "  [db.seed]",
        `  sql_paths = ["./seed.sql", "${seedPath}"]`,
      );
    }
  }

  return {
    code: 0,
    output: lines.join("\n"),
    data: {
      file,
      files: applied.changes,
      tables: statements.length,
      applied: args.apply === true,
      listed,
    },
  };
}

interface TenantRow {
  readonly id: string;
  readonly slug: string | null;
  readonly name: string | null;
}

async function runTenantSeed(
  config: ResolvedConfig,
  args: SeedFlags,
  env: CliEnv,
  open: typeof connect,
  dbUrl: string | undefined,
  requireConsent: (request: ConsentRequest) => void,
): Promise<CommandResult> {
  const tenant = args.tenant ?? "*";
  const entry = args.entry ?? config.seed.perTenant;
  const seed = await importExport(resolve(config.root, entry), "seed");

  if (!isTenantSeed(seed)) {
    return {
      code: 1,
      errorCode: "invalid_input",
      error: `${display(config.root, entry)} must export defineTenantSeed(...) as \`seed\` or default.`,
    };
  }

  const query = tenantsQuery(moduleLayout(config), config.blockNames, tenant);

  if (!query) {
    return {
      code: 1,
      errorCode: "invalid_input",
      error:
        "seed --tenant looks tenants up in the organizations block. Add it with `better-supabase add organizations`.",
    };
  }

  if (args["dry-run"] === true || args.check === true) {
    return {
      code: 0,
      output: `Would insert ${display(config.root, entry)} for ${tenant === "*" ? "every organization" : tenant}.`,
      data: { tenant, applied: false, tenants: [] },
    };
  }

  const url = await databaseUrl(
    config,
    env,
    dbUrl,
    args.stack ?? env.BSB_STACK,
  );

  if (!isLocalDatabaseUrl(url)) {
    requireConsent({
      effect: "database-write",
      detail: `seed --tenant inserts rows into ${databaseHost(url)}`,
    });
  }

  const { client, close } = await open(url);
  let tenants: TenantRow[];

  try {
    const result = await client.query<TenantRow>(query.text, [...query.values]);

    tenants = result.rows;

    if (tenants.length === 0) {
      return {
        code: 1,
        errorCode: "not_found",
        error:
          tenant === "*"
            ? "There are no organizations to seed."
            : `No organization has the slug or id "${tenant}".`,
      };
    }

    await client.query("begin");

    try {
      for (const row of tenants) {
        const target = {
          id: row.id,
          ...(row.slug === null ? {} : { slug: row.slug }),
          ...(row.name === null ? {} : { name: row.name }),
        };

        for (const text of seed.statements(target)) {
          await client.query(text);
        }
      }

      await client.query("commit");
    } catch (error) {
      await client.query("rollback");
      throw error;
    }
  } finally {
    await close();
  }

  const labels = tenants.map((row) => row.slug ?? row.id);

  return {
    code: 0,
    output: `Inserted ${display(config.root, entry)} for ${labels.join(", ")} (existing rows were kept).`,
    data: { tenant, applied: true, tenants: labels },
  };
}

export const seedCommand: AnyCommand = defineCliCommand({
  meta: commandMeta("db seed"),
  args: { ...ARGS, ...DB_URL_STDIN_ARG, ...STACK_ARG, ...PLAN_ARGS },
  run: async (args, { config, env, io, log, requireConsent }) => {
    const dbUrl = await stdinDatabaseUrl(args["db-url-stdin"], io);

    const seed = (): Promise<CommandResult> =>
      runSeed(config, args, env, connect, dbUrl, requireConsent);

    return args.apply === true || args.tenant !== undefined
      ? log.progress("Inserting the seed rows", seed)
      : seed();
  },
});
