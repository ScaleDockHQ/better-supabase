import { posix } from "node:path";

export type ScaffoldFramework = "hono" | "next";

export const SCAFFOLD_FRAMEWORKS: readonly ScaffoldFramework[] = [
  "hono",
  "next",
];

export interface ScaffoldContext {
  readonly framework: ScaffoldFramework;
  /** `src` or `.`. */
  readonly srcDir: string;
  readonly tsExtensions: boolean;
  /** The API module's name: `api` writes `lib/api.ts` and `lib/api.generated.ts`. */
  readonly name: string;
  /** Where the resources are served, `/api` by default. */
  readonly basePath: string;
  readonly tables: readonly string[];
}

export interface ScaffoldFile {
  readonly path: string;
  readonly contents: string;
  /** Rewritten on every run; otherwise written once and owned by the developer. */
  readonly generated: boolean;
}

export const GENERATED_HEADER =
  "// @generated by better-supabase scaffold. Do not edit; run `better-supabase scaffold api` again instead.";

const join = (...parts: string[]): string =>
  posix.normalize(posix.join(...parts));

function importFrom(
  context: ScaffoldContext,
  from: string,
  to: string,
): string {
  let path = posix.relative(posix.dirname(from), to);

  if (!path.startsWith(".")) {
    path = `./${path}`;
  }

  if (context.tsExtensions) {
    return path;
  }

  return path.replace(/\.tsx?$/, "").replace(/^(\.\.?\/.+)\/index$/, "$1");
}

const quote = (value: string): string => JSON.stringify(value);

function generatedModule(context: ScaffoldContext): string {
  const names = context.tables.map(quote).join(", ");

  const resources = context.tables
    .map(
      (table) =>
        `  ${/^[A-Za-z_$][\w$]*$/.test(table) ? table : quote(table)}: true,`,
    )
    .join("\n");

  return `${GENERATED_HEADER}

/** The tables served as REST resources and documented in the API model. */
export const tableNames = [${names}] as const;

export const resources = {
${resources}
} as const;

export const basePath = ${quote(context.basePath)};
`;
}

function apiModule(
  context: ScaffoldContext,
  path: string,
  generated: string,
): string {
  const lib = join(context.srcDir, "lib", "supabase", "index.ts");

  return `import { defineApi } from 'better-supabase/spec';

import { betterSupabase } from '${importFrom(context, path, lib)}';
import { basePath, resources, tableNames } from '${importFrom(context, path, generated)}';

export { basePath, resources, tableNames };

/**
 * The API model. Every OpenAPI version, and the other spec formats, render
 * from it, and \`better-supabase spec emit\` reads it. Describe resources,
 * add list queries and custom routes here: this file is yours, and
 * \`better-supabase scaffold api\` never rewrites it.
 */
export const api = defineApi(betterSupabase, {
  info: { title: 'API', version: '1.0.0' },
  basePath,
  resources,
});
`;
}

function nextFiles(context: ScaffoldContext, api: string): ScaffoldFile[] {
  const routeDir = join(context.srcDir, "app", context.basePath);
  const resources = join(routeDir, "[...path]", "route.ts");
  const spec = join(routeDir, "openapi.json", "route.ts");
  const server = join(context.srcDir, "lib", "supabase", "server.ts");

  return [
    {
      path: resources,
      generated: false,
      contents: `import { basePath, resources } from '${importFrom(context, resources, api)}';
import { bs } from '${importFrom(context, resources, server)}';

export const { GET, POST, PATCH, PUT, DELETE } = bs.resources(resources, { basePath });
`,
    },
    {
      path: spec,
      generated: false,
      contents: `import { specResponse } from 'better-supabase/spec';

import { api } from '${importFrom(context, spec, api)}';

const { document } = api.openapi();

export const GET = (request: Request) => specResponse(document, request);
`,
    },
  ];
}

function honoFiles(context: ScaffoldContext, api: string): ScaffoldFile[] {
  const path = join(context.srcDir, `${context.name}-routes.ts`);
  const server = join(context.srcDir, "server.ts");

  return [
    {
      path,
      generated: false,
      contents: `import { specResponse } from 'better-supabase/spec';

import { api, basePath, tableNames } from '${importFrom(context, path, api)}';
import type { bs as server } from '${importFrom(context, path, server)}';

const { document } = api.openapi();

/**
 * The OpenAPI document and a REST resource per table. Mount it in
 * server.ts with \`.route('/', apiRoutes(bs))\`.
 */
export function apiRoutes(bs: typeof server) {
  const routes = bs
    .app()
    .get(\`\${basePath}/openapi.json\`, (c) => specResponse(document, c.req.raw))
    .use(\`\${basePath}/*\`, bs.middleware());
  for (const table of tableNames) routes.route(\`\${basePath}/\${table}\`, bs.resource(table));
  return routes;
}
`,
    },
  ];
}

/** The files `scaffold api` writes for a framework. */
export function scaffoldApiFiles(context: ScaffoldContext): ScaffoldFile[] {
  const lib = join(context.srcDir, "lib");
  const generated = join(lib, `${context.name}.generated.ts`);
  const api = join(lib, `${context.name}.ts`);

  const shared: ScaffoldFile[] = [
    { path: generated, generated: true, contents: generatedModule(context) },
    {
      path: api,
      generated: false,
      contents: apiModule(context, api, generated),
    },
  ];

  switch (context.framework) {
    case "next": {
      return [...shared, ...nextFiles(context, api)];
    }

    case "hono": {
      return [...shared, ...honoFiles(context, api)];
    }

    default: {
      const unknown: never = context.framework;
      throw new Error(`Unknown framework: ${String(unknown)}`);
    }
  }
}

/** What to do after the files are written. */
export function scaffoldNextSteps(
  context: ScaffoldContext,
  specsEntry: string,
): string[] {
  const api = join(context.srcDir, "lib", `${context.name}.ts`);
  const steps: string[] = [];

  if (context.framework === "hono") {
    steps.push(
      `Mount the routes in ${join(context.srcDir, "server.ts")}: \`.route('/', apiRoutes(bs))\`.`,
    );
  }

  if (specsEntry !== api) {
    steps.push(
      `Set \`specs: { entry: '${api}' }\` in better-supabase.config.ts, so \`better-supabase spec emit\` reads the API model.`,
    );
  }

  steps.push(
    `Describe the resources in ${api}; \`scaffold api\` only rewrites ${context.name}.generated.ts.`,
  );

  return steps;
}
