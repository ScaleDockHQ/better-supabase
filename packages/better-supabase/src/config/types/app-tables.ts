import type { FieldFormatName } from "../../core/contracts/field-formats.ts";

import { FIELD_FORMAT_NAMES } from "../../core/contracts/field-formats.ts";

/**
 * The column types an app table may use. Money is a `bigint` of minor units
 * next to a `text` currency column (ADR 0024 and 0037), never `numeric`.
 */
export const APP_COLUMN_TYPES = [
  "text",
  "uuid",
  "integer",
  "bigint",
  "numeric",
  "boolean",
  "timestamptz",
  "date",
  "jsonb",
  "text[]",
] as const;

export type AppColumnType = (typeof APP_COLUMN_TYPES)[number];

/**
 * What a reference does when the row it points at is deleted
 * (`references.onDelete`).
 */
export const APP_ON_DELETE_ACTIONS = [
  "cascade",
  "restrict",
  "set null",
  "no action",
] as const;

export type AppOnDeleteAction = (typeof APP_ON_DELETE_ACTIONS)[number];

/**
 * What a column references: another app table, `auth.users` (`{ table:
 * "auth.users" }`), or a logical table of an installed block (`{ block: "crm",
 * table: "contacts" }`), which follows the block's renames.
 */
export type AppReferenceTarget =
  | { readonly table: string }
  | { readonly block: string; readonly table: string };

export type AppReference = AppReferenceTarget & {
  /** Defaults to `no action`. */
  readonly onDelete?: AppOnDeleteAction;
};

/**
 * What a column holds, beyond its Postgres type. `email`, `url`, `rating` and
 * `percent` add a check; the others tell the UI and `gen` how to show the
 * value. `FIELD_FORMATS` lists the types each fits and its input.
 */
export const APP_COLUMN_FORMATS: typeof FIELD_FORMAT_NAMES = FIELD_FORMAT_NAMES;

export type AppColumnFormat = FieldFormatName;

export interface AppColumnConfig {
  readonly type: AppColumnType;
  /** Defaults to true. */
  readonly nullable?: boolean;
  /**
   * The column default, from an allowlist: `now()`, `gen_random_uuid()`,
   * `auth.uid()`, `true`, `false`, a number, a `'quoted'` text literal, and
   * `'{}'` or `'[]'` for `jsonb` and `text[]`.
   */
  readonly default?: string;
  readonly unique?: boolean;
  readonly references?: AppReference;
  /** What the column holds; see `APP_COLUMN_FORMATS`. */
  readonly format?: AppColumnFormat;
  /**
   * The schema-qualified domain the column takes as its type, such as
   * `bsb.email`, in place of the format's inline check. Only `migrate
   * schema-first` and the preset writers set it (ADR 0102); it isn't a config
   * key.
   */
  readonly domain?: string;
  /**
   * The values a `text` column (single select) or each element of a `text[]`
   * column (multi-select) may take, checked by the database.
   */
  readonly options?: readonly string[];
  /** The smallest value of a number column, or the shortest `text`. */
  readonly min?: number;
  /** The largest value of a number column, or the longest `text`. */
  readonly max?: number;
  /** Rendered as `comment on column`. */
  readonly comment?: string;
  /**
   * An `integer` or `bigint` the database numbers (`generated by default as
   * identity`).
   */
  readonly identity?: boolean;
  /**
   * Who reaches the column, through column grants (ADR 0051). By default
   * signed-in users read and write it, within the row's policies. `read` lets
   * them read it while only the service role, triggers and defaults write it;
   * `server` hides it from them, so only the service role reads and writes it.
   */
  readonly access?: AppColumnAccess;
  /**
   * Stores the column encrypted with the row's tenant (or user) data key from
   * Supabase Vault, through the `field-encryption` block. Signed-in users write
   * plaintext and never select the column; they read it through
   * `public.<table>_reveal(ids)`, which checks the row's policy and decrypts.
   * It can't be unique, a reference, an identity, indexed or searched.
   */
  readonly encrypted?: boolean;
  /**
   * Adds `<column>_lookup bytea` to an encrypted column: an HMAC-SHA256 of the
   * value, lowercased and without whitespace, under the owner's lookup key from
   * Vault. `public.<table>_find(column, value)` finds rows by an equal value
   * without decrypting any. Needs `encrypted: true`.
   */
  readonly lookup?: boolean;
}

export const APP_COLUMN_ACCESS = ["read", "server"] as const;

export type AppColumnAccess = (typeof APP_COLUMN_ACCESS)[number];

/**
 * A table the app owns, created in `public` by `better-supabase upgrade` next
 * to the block files. Every table gets `id`, the scope column and (unless
 * `timestamps: false`) `created_at` and `updated_at`.
 */
export interface AppTableConfig {
  /** The table's own columns, keyed by lower snake name. */
  readonly columns?: Readonly<Record<string, AppColumnConfig>>;
  /**
   * Who reaches a row. `inherit` (the default) follows `sql.scope`: per tenant,
   * members of the row's tenant; per user, the row's user. `user` keeps rows
   * per user in any scope, and `none` lets signed-in users read every row while
   * only the service role writes.
   */
  readonly scope?: "inherit" | "user" | "none";
  /** `created_at` and `updated_at`. Defaults to true. */
  readonly timestamps?: boolean;
  /**
   * The id's type: `uuid` (the default, `gen_random_uuid()`) or `bigint` (an
   * identity). A reference to the table needs a column of the same type.
   */
  readonly id?: "uuid" | "bigint";
  /** Sets of columns that are unique together, each a unique constraint. */
  readonly unique?: readonly (readonly string[])[];
  /**
   * Sets of columns to index, in order. Reference and scope columns already
   * have one.
   */
  readonly indexes?: readonly (readonly string[])[];
  /** Rendered as `comment on table`. */
  readonly comment?: string;
  /**
   * Registers the table as a subject (ADR 0043), so blocks that attach rows to
   * subjects (comments, attachments, tags, versions, search and others) reach
   * its rows without a `subjects` entry.
   */
  readonly subject?: AppTableSubject;
  /**
   * Values computed from the rows of another app table that references this
   * one, keyed by the column name they get in `public.<table>_view` (ADR
   * 0044).
   */
  readonly rollups?: Readonly<Record<string, AppRollupConfig>>;
  /**
   * Columns of the row a reference points at, keyed by the column name they get
   * in `public.<table>_view` (ADR 0044).
   */
  readonly lookups?: Readonly<Record<string, AppLookupConfig>>;
  /**
   * Emits an outbox event for each insert, update and delete (ADR 0048):
   * `<subject type or table>.created`, `.updated` and `.deleted`. Needs the
   * `outbox` block.
   */
  readonly events?: true | AppTableEvents;
  /**
   * Writes an audit log entry in the `read` category for each call of
   * `public.<table>_reveal`: who read which rows and when, one entry per tenant
   * per call. Needs an `encrypted` column and the `audit` block.
   */
  readonly auditReads?: boolean;
}

export const APP_TABLE_EVENT_KINDS = ["created", "updated", "deleted"] as const;

export type AppTableEventKind = (typeof APP_TABLE_EVENT_KINDS)[number];

/** Which writes emit an event and which column values its payload carries. */
export interface AppTableEvents {
  /** Defaults to all three. */
  readonly on?: readonly AppTableEventKind[];
  /**
   * Columns whose values go in the payload. By default it holds the row id and,
   * for updates, the names of the changed columns.
   */
  readonly include?: readonly string[];
}

export const APP_ROLLUP_AGGREGATES = [
  "count",
  "sum",
  "min",
  "max",
  "avg",
] as const;

export type AppRollupAggregate = (typeof APP_ROLLUP_AGGREGATES)[number];

/**
 * An aggregate over the rows of `table` whose `via` column references this
 * table: `{ table: "tasks", via: "project_id", aggregate: "count" }`.
 */
export interface AppRollupConfig {
  /** The app table whose rows are aggregated. */
  readonly table: string;
  /** The column of `table` that references this table. */
  readonly via: string;
  /** `sum` of no rows is 0; `min`, `max` and `avg` of no rows are null. */
  readonly aggregate: AppRollupAggregate;
  /**
   * The column of `table` the aggregate reads: a number for `sum` and `avg`, a
   * number, date, time or text for `min` and `max`. `count` takes none and
   * counts rows.
   */
  readonly column?: string;
  /**
   * Only the rows whose select column (a `text` column with `options`) holds
   * `equals`.
   */
  readonly where?: { readonly column: string; readonly equals: string };
}

/** The `column` of the app table row that this table's `via` column references. */
export interface AppLookupConfig {
  /** A column of this table that references another app table. */
  readonly via: string;
  /** A column of the referenced table. */
  readonly column: string;
}

/**
 * The subject an app table registers. The table, id type and tenant column come
 * from the table itself.
 */
export interface AppTableSubject {
  /** The subject type, lowercase letters, digits and underscores. */
  readonly type: string;
  /** The column `subject_title` returns. */
  readonly title?: string;
  /**
   * The path `subject_url` returns, with `{column}` placeholders:
   * `/projects/{id}`.
   */
  readonly url?: string;
  /** The columns a search index reads. */
  readonly search?: {
    readonly title?: string;
    readonly body?: readonly string[];
  };
  /**
   * A permission key per action that `can_subject` checks; see
   * `SubjectConfig.permissions`.
   */
  readonly permissions?: Readonly<Record<string, string>>;
  /**
   * Adds a `rank text collate "C"` column for `move()` (ADR 0021), ordered
   * within `group` when set.
   */
  readonly rank?: true | { readonly group?: string };
  /**
   * Adds a `deleted_at timestamptz` column that blocks treat as the soft-delete
   * time.
   */
  readonly softDelete?: boolean;
  /**
   * Registers the table with the versions block: `true` snapshots every column
   * of the table on each change; `columns` and `auto` narrow it.
   */
  readonly versions?: true | AppTableVersions;
}

/** What the versions block keeps of an app table's rows. */
export interface AppTableVersions {
  /**
   * The columns a snapshot copies and a restore writes back; every column of
   * the table by default.
   */
  readonly columns?: readonly string[];
  /** Snapshot on each change to `columns`, debounced; `true` by default. */
  readonly auto?: boolean;
}

export type AppTablesConfig = Readonly<Record<string, AppTableConfig>>;
