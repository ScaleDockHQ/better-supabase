import type { AppTableConfig } from "../../config/types/app-tables.ts";

import { sqlIdent, sqlString } from "../../core/template.ts";
import { addNotNullCheck, notNullCheckName } from "../shared.ts";

const SCHEMA = "public";

/**
 * A `tables.<name>` entry over a table the app's own schema creates
 * (`layout.ownTables`), as the enrich SQL needs it.
 */
export interface EnrichTable {
  readonly name: string;
  readonly config: AppTableConfig;
  /** The scope column, its type without `not null`; `undefined` in `none`. */
  readonly scope:
    | { readonly name: string; readonly addable: string }
    | undefined;
  /** Where the app creates the table: its schema file, or `database`. */
  readonly source: string;
  /** The columns the app's table already has, when they are known. */
  readonly existing: ReadonlySet<string>;
}

const qualified = (table: string): string =>
  `${sqlIdent(SCHEMA)}.${sqlIdent(table)}`;

/**
 * Each implicit column the app's table lacks, added with `add column if not
 * exists`, nullable unless it has a default. The id is unique instead of the
 * primary key, which the table may already have. The scope column gets a `not
 * valid` not-null check, which `db backfill` and `doctor --fix` (BS236)
 * complete.
 */
export function enrichSql(table: EnrichTable): string {
  const target = qualified(table.name);

  const columns = [
    ...(table.existing.has("id")
      ? []
      : [
          table.config.id === "bigint"
            ? "id bigint generated by default as identity unique"
            : "id uuid not null default gen_random_uuid() unique",
        ]),
    ...(table.scope && !table.existing.has(table.scope.name)
      ? [`${sqlIdent(table.scope.name)} ${table.scope.addable}`]
      : []),
    ...(table.config.timestamps === false
      ? []
      : ["created_at", "updated_at"]
          .filter((column) => !table.existing.has(column))
          .map((column) => `${column} timestamptz not null default now()`)),
  ];

  const where = table.source === "database" ? "the database" : table.source;

  return [
    `-- ${target} is the app's table (${where}): tables.${table.name} adds only the columns it lacks.`,
    ...columns.map(
      (column) => `alter table ${target} add column if not exists ${column};`,
    ),
    ...(table.scope
      ? [addNotNullCheck({ table: target, column: sqlIdent(table.scope.name) })]
      : []),
  ].join("\n");
}

/**
 * The pgTAP checks of an enriched table: its scope policies among the app's own
 * (`policies` lists them), the scope column, and its not-null check.
 */
export function enrichChecks(
  table: EnrichTable,
  policies: readonly string[],
): readonly string[] {
  const name = sqlString(table.name);
  const label = `${SCHEMA}.${table.name}`;
  const regclass = `${sqlString(qualified(table.name))}::regclass`;
  const list = policies.map((policy) => sqlString(policy)).join(", ");

  const checks = [
    `select extensions.ok(array[${list}]::name[] <@ array(select p.policyname from pg_catalog.pg_policies p where p.schemaname = '${SCHEMA}' and p.tablename = ${name}), ${sqlString(`${label} has the policies for its scope`)});`,
  ];

  if (table.scope) {
    const constraint = notNullCheckName(
      qualified(table.name),
      sqlIdent(table.scope.name),
    );

    checks.push(
      `select extensions.has_column('${SCHEMA}', ${name}, ${sqlString(table.scope.name)}, ${sqlString(`${label} has the scope column ${table.scope.name}`)});`,
      `select extensions.ok(exists (select 1 from pg_catalog.pg_constraint k where k.conrelid = ${regclass} and k.conname = ${sqlString(constraint)} and k.contype = 'c'), ${sqlString(`new rows of ${label} must fill ${table.scope.name}`)});`,
    );
  }

  return checks;
}
