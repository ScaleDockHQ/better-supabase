import type { BlockSqlContext } from "./context.ts";
import type { BlockSql } from "./module-types.ts";

import { ENTITY_KEY_RENAMES } from "../core/renames.ts";
import { moduleContext } from "./module-context.ts";
import {
  isOperationModule,
  moduleOperations,
} from "./modules/permissions-model.ts";
import { OPTIONAL_MODULE_PERMISSIONS } from "./optional-permissions.ts";
import { resolveBlocks } from "./registry.ts";

/** The names a module's config keys accept, read from its definition. */
export interface BlockSqlNameSet {
  readonly name: string;
  readonly tables: Readonly<Record<string, readonly string[]>>;
  readonly functions: readonly string[];
  readonly actions: readonly string[];
  readonly hooks: readonly string[];
  /** Entity to the default column names of its table. */
  readonly entities: Readonly<Record<string, readonly string[]>>;
  readonly primary: string | undefined;
  /** Entity keys before the 0.47 renames, which still resolve. */
  readonly formerKeys: readonly string[];
}

/**
 * The function names `module` writes under the default layout: every name it
 * passes to `fn` or `fnName` while it builds, plus its contract.
 */
function functionsOf(module: BlockSql): string[] {
  const ctx = moduleContext(
    module.name,
    {},
    resolveBlocks([module.name], {}).map((each) => each.name),
  );

  const found = new Set<string>();

  const probe: BlockSqlContext = {
    ...ctx,
    fn: (name) => {
      found.add(name);

      return ctx.fn(name);
    },
    fnName: (name) => {
      found.add(name);

      return ctx.fnName(name);
    },
  };

  module.build(probe, {});
  module.data?.(probe, {});

  for (const each of module.contract?.(probe) ?? []) {
    found.add(each.name);
  }

  return [...found].toSorted();
}

export function moduleNameSet(module: BlockSql): BlockSqlNameSet {
  const names = module.names;
  const entities = Object.entries(names?.entities ?? {});

  return {
    name: module.name,
    tables: Object.fromEntries(
      Object.entries(names?.tables ?? {}).map(([table, spec]) => [
        table,
        Object.keys(spec.columns),
      ]),
    ),
    functions: functionsOf(module),
    actions: [
      ...(isOperationModule(module.name)
        ? Object.keys(moduleOperations(module.name))
        : []),
      ...Object.keys(OPTIONAL_MODULE_PERMISSIONS[module.name] ?? {}),
    ],
    hooks: [...(names?.hooks ?? [])],
    entities: Object.fromEntries(
      entities.map(([key, spec]) => [
        key,
        Object.values(
          (spec.table === undefined ? undefined : names?.tables[spec.table])
            ?.columns ?? {},
        ),
      ]),
    ),
    primary: entities.find(([, spec]) => spec.primary === true)?.[0],
    formerKeys: Object.keys(ENTITY_KEY_RENAMES[module.name] ?? {}),
  };
}

function union(values: readonly string[]): string {
  return values.length === 0
    ? "never"
    : values.map((value) => JSON.stringify(value)).join(" | ");
}

function entityLines(
  entities: Readonly<Record<string, readonly string[]>>,
): string {
  const lines = Object.entries(entities).map(
    ([entity, columns]) =>
      `      readonly ${JSON.stringify(entity)}: ${union(columns)};`,
  );

  return lines.length === 0
    ? "    readonly entities: {};"
    : `    readonly entities: {\n${lines.join("\n")}\n    };`;
}

/** `src/blocks/name-registry.generated.ts` for `modules`. */
export function formatNameRegistry(modules: readonly BlockSql[]): string {
  const entries = modules
    .map(moduleNameSet)
    .toSorted((a, b) => a.name.localeCompare(b.name))
    .map((names) => {
      const tables = Object.entries(names.tables)
        .map(
          ([table, columns]) =>
            `      readonly ${JSON.stringify(table)}: ${union(columns)};`,
        )
        .join("\n");

      return [
        `  readonly ${JSON.stringify(names.name)}: {`,
        tables === ""
          ? "    readonly tables: {};"
          : `    readonly tables: {\n${tables}\n    };`,
        `    readonly functions: ${union(names.functions)};`,
        `    readonly actions: ${union(names.actions)};`,
        `    readonly hooks: ${union(names.hooks)};`,
        entityLines(names.entities),
        `    readonly primary: ${names.primary === undefined ? "never" : JSON.stringify(names.primary)};`,
        `    readonly formerKeys: ${union(names.formerKeys)};`,
        "  };",
      ].join("\n");
    });

  return [
    "// Generated by scripts/build-catalog.ts from SQL_MODULES. Do not edit; run",
    "// `pnpm catalog`.",
    "",
    "/** The names each module's `blocks.<name>` config keys accept. */",
    "export interface BlockNameRegistry {",
    ...entries,
    "}",
    "",
  ].join("\n");
}
