/**
 * Every route of the signed-in app with its archetype, the seeded URL a test
 * opens, its database budget, whether the page exports `instant = true` and
 * whether it is a scale route (run against tier L). One entry per `page.tsx`
 * under `src/app/[locale]/(app)`; `tests/routes-manifest.test.ts` fails when a
 * page has no entry or an entry has no page.
 *
 * `maxCalls` and `maxWaves` start as ceilings per archetype. The first
 * `budgets.spec.ts` run on a seeded stack prints the measured numbers (`pnpm
 * example:perf-report`); tighten an entry to the measurement plus slack, and
 * never loosen one without a finding in docs/agents/example-findings.md. A
 * `url` of `null` needs an id the seed does not fix yet.
 */

export type RouteArchetype =
  | "dashboard"
  | "overview"
  | "detail"
  | "settings"
  | "editor"
  | "board"
  | "conversation"
  | "other";

