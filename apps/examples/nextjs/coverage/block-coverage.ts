/**
 * Maps every catalog block to the screens that show it, and every preset to a
 * tour of routes. `scripts/check-example-coverage.ts` (`pnpm
 * check:example-coverage`) fails when a block or preset has no entry, when a
 * listed route has no `page.tsx`, or when an entry names an unknown block.
 *
 * "Covered" means a user reaches the block's main read and its main write from
 * a screen. A `planned` entry names the phase of the example plan that builds
 * the screen, and the script prints how many are left.
 */

export type CoverageEntry =
  | { readonly routes: readonly string[] }
  | { readonly noUi: string }
  | {
      readonly planned: string;
      /** The page that exists today, if the block has a thin version of it. */
      readonly routes?: readonly string[];
    };

const at = (...routes: string[]): CoverageEntry => ({ routes });
const none = (noUi: string): CoverageEntry => ({ noUi });
const later = (planned: string, ...routes: string[]): CoverageEntry =>
  routes.length > 0 ? { planned, routes } : { planned };

