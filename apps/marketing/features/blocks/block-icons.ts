const byName = new Map<string, LucideIcon>(Object.entries(BLOCK_ICONS));

/** The block's own icon, or its category's while a new block has none yet. */
export function blockIcon(name: string, category: string): LucideIcon {
  return byName.get(name) ?? categoryStyle(category).icon;
}
